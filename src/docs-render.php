/*
 * Rendering for ps-module docs (used by docs.php): manuals as print-ready HTML, PDF through a chain
 * of engines, marketing sheets for the Addons product page and the overview page docs/index.html.
 *
 * PDF engines, in the order of docs.json > pdf.engines (default):
 *   docker       Chromium in the docs-tools image with Noto fonts for every script (best result)
 *   chrome       a local Chrome, Edge or Chromium in headless mode (--print-to-pdf); uses the system fonts
 *   wkhtmltopdf  when installed (old WebKit: simpler layout)
 *   dompdf       when the module has dompdf/dompdf; only for Latin, Cyrillic and Greek (no Arabic shaping, no CJK)
 * When none works, the print-ready HTML stays and the reason is reported.
 */

declare(strict_types=1);

