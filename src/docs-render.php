/**
 * State of the generated output: are there manuals, PDFs and marketing sheets for every language, for this version?
 *
 * @param array<string, mixed> $ctx
 *
 * @return array{state: string, message: string}
 */
function docs_outputs_state(array $ctx): array
{
    $manifest = docs_read_json($ctx['docs'] . '/build-manifest.json') ?? [];
    $missing = [];
    foreach ($ctx['languages'] as $iso) {
        foreach (["manual/$iso/manual.html" => 'manual', "manual/$iso/readme_$iso.pdf" => 'pdf', "marketing/$iso/marketing.html" => 'marketing'] as $file => $label) {
            if (!is_file($ctx['docs'] . '/' . $file)) {
                $missing[$label][] = $iso;
            }
        }
    }
    $frames = docs_frames_state($ctx)['missing'];
    if ($frames !== []) {
        $missing['framed screenshots'][] = count($frames) . ' (' . implode(' ', array_slice($frames, 0, 4)) . (count($frames) > 4 ? ' ...' : '') . ')';
    }
    if ($missing !== []) {
        $parts = [];
        foreach ($missing as $label => $languages) {
            $parts[] = "$label: " . implode(' ', $languages);
        }
        ps_vlog('generated output: missing ' . implode('; ', $parts));

        return ['state' => 'missing', 'message' => 'not generated yet (' . implode('; ', $parts) . ')'];
    }
    ps_vlog('generated output: all files there; last build ' . ($manifest['built']['time'] ?? '?') . ', version ' . ($manifest['built']['version'] ?? '?') . ', content hash ' . ($manifest['built']['content'] ?? '?') . ' (now ' . docs_content_hash($ctx) . ')');
    if (($manifest['built']['version'] ?? '') !== $ctx['version']) {
        return ['state' => 'stale', 'message' => 'built for version ' . ($manifest['built']['version'] ?? '?') . ', the module is ' . $ctx['version']];
    }
    if (($manifest['built']['content'] ?? '') !== docs_content_hash($ctx)) {
        return ['state' => 'stale', 'message' => 'the docs content changed after the last build (' . substr((string) ($manifest['built']['time'] ?? ''), 0, 16) . ')'];
    }
    if (($manifest['built']['fingerprint'] ?? '') !== dod_fingerprint($ctx['repo'])) {
        return ['state' => 'stale', 'message' => 'built on older module code (' . substr((string) ($manifest['built']['time'] ?? ''), 0, 16) . ')'];
    }

    return ['state' => 'ok', 'message' => 'up to date (' . substr((string) ($manifest['built']['time'] ?? ''), 0, 16) . ')'];
}
