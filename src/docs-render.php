/**
 * Renders docs/manual/<iso>/manual.html for each language; returns the files written.
 *
 * @param array<string, mixed> $ctx
 * @param string[] $languages
 * @param array<string, mixed> $manifest updated with the hash and date of each manual
 *
 * @return array<string, string> iso => manual.html
 */
function docs_render_manuals(array $ctx, array $languages, array &$manifest): array
{
    $files = [];
    foreach ($languages as $iso) {
        $manual = docs_load_manual($ctx, $iso);
        if ($manual === null) {
            echo "  $iso  manual.md missing: not rendered\n";
            continue;
        }
        $dir = $ctx['docs'] . "/manual/$iso";
        if (!is_dir($dir)) {
            mkdir($dir, 0775, true);
        }
        $html = docs_manual_html($ctx, $iso, $manual, $dir);
        // The date on the cover only changes when the content changes (no new PDF every day).
        $hash = sha1($html);
        $previous = $manifest['manual'][$iso] ?? [];
        $date = ($previous['hash'] ?? '') === $hash && isset($previous['date']) ? (string) $previous['date'] : date('Y-m-d');
        $manifest['manual'][$iso] = ['hash' => $hash, 'date' => $date, 'version' => $ctx['version']];
        file_put_contents("$dir/manual.html", str_replace('%%DOCS_DATE%%', $date, $html));
        ps_vlog("manual $iso: wrote $dir/manual.html (" . round(strlen($html) / 1024) . ' KB, date ' . $date . (($previous['hash'] ?? '') === $hash ? ', content unchanged' : ', content changed') . ')');
        $files[$iso] = "$dir/manual.html";
    }

    return $files;
}

/**
 * The complete HTML document of a manual (cover, table of contents, content), with the date as %%DOCS_DATE%%.
 *
 * @param array<string, mixed> $ctx
 * @param array{meta: array<string, string>, body: string, sections: array<int, array{title: string, text: string}>} $manual
 */
function docs_manual_html(array $ctx, string $iso, array $manual, string $outDir): string
{
    $ctx = docs_localize($ctx, $iso);
    $meta = $manual['meta'];
    $shots = [];
    foreach ((array) ($ctx['config']['screenshots'] ?? []) as $shot) {
        $shots[(string) ($shot['id'] ?? '')] = $shot;
    }
    $images = static function (string $src) use ($ctx, $iso, $outDir, $shots): ?array {
        if (str_starts_with($src, 'screenshot:')) {
            $id = substr($src, 11);
            // The framed screenshot (caption printed on the frame, so no caption under it), else the raw one.
            $framed = docs_frame_config($ctx)['manual'] !== false ? docs_framed_file($ctx, $iso, $id) : '';
            if ($framed !== '') {
                return ['src' => docs_relative_path($outDir, $framed), 'class' => 'framed', 'caption' => false];
            }
            $file = docs_screenshot_file($ctx, $iso, $id);
            if ($file === null) {
                return null;
            }
            $viewport = $shots[$id]['viewport'] ?? 'desktop';

            return ['src' => docs_relative_path($outDir, $file), 'class' => is_string($viewport) ? $viewport : 'custom'];
        }
        if (preg_match('#^https?://#', $src)) {
            return ['src' => $src];
        }
        $file = docs_content_image($ctx, $iso, $src);

        return $file === null ? null : ['src' => docs_relative_path($outDir, $file)];
    };
    $headings = [];
    $content = docs_md_render(docs_fill($ctx, $manual['body']), $images, $headings);

    $toc = '';
    $open = false;
    foreach ($headings as $h) {
        if ($h['level'] === 2) {
            $toc .= ($open ? "</ol></li>\n" : '') . '<li><a href="#' . $h['id'] . '">' . docs_e($h['text']) . '</a><ol>';
            $open = true;
        } elseif ($h['level'] === 3 && $open) {
            $toc .= '<li><a href="#' . $h['id'] . '">' . docs_e($h['text']) . '</a></li>';
        }
    }
    $toc = (string) preg_replace('#<ol></li>#', '</li>', $toc . ($open ? "</ol></li>\n" : ''));
    $toc = str_replace('<ol></ol>', '', $toc);

    $logoFile = $ctx['module_dir'] . '/logo.png';
    $logo = is_file($logoFile) ? '<img class="cover-logo" src="' . docs_data_uri($logoFile) . '" alt="">' : '';
    $title = docs_fill($ctx, $meta['title'] ?? 'Manual');
    $summary = docs_fill($ctx, $meta['summary'] ?? '');
    $accent = preg_match('/^#[0-9a-fA-F]{6}$/', (string) ($ctx['config']['manual']['accent'] ?? '')) ? $ctx['config']['manual']['accent'] : '#1f4fd1';
    $running = str_replace(['\\', '"'], ['\\\\', '\\"'], $ctx['display_name'] . ' · ' . $title);
    $css = (string) file_get_contents(DOCS_RESOURCES . '/docs/manual.css');
    $dir = docs_is_rtl($ctx, $iso) ? 'rtl' : 'ltr';
    $psRange = 'PrestaShop ' . $ctx['ps_min'] . ($ctx['ps_tested'] !== '' && $ctx['ps_tested'] !== $ctx['ps_min'] ? ' – ' . $ctx['ps_tested'] : '+');
    $author = $ctx['author'] !== '' ? '<dl class="cover-author"><dd>' . docs_e($ctx['author']) . '</dd></dl>' : '';

    return '<!doctype html>
<html lang="' . docs_e($iso) . '" dir="' . $dir . '">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<meta name="generator" content="ps-module docs">
<title>' . docs_e($ctx['display_name'] . ' ' . $ctx['version'] . ' – ' . $title) . '</title>
<style>
' . $css . '
:root { --accent: ' . $accent . '; }
@page { @top-right { content: "' . $running . '"; font-size: 8pt; color: #8a93a3; font-family: ' . docs_font_stack($iso) . '; }
  @bottom-center { content: counter(page) " / " counter(pages); direction: ltr; unicode-bidi: isolate; font-family: ' . docs_font_stack($iso) . '; } }
@page :first { @top-right { content: none; } }
</style>
</head>
<body>
<section class="sheet cover">
  <div class="cover-band">
    ' . $logo . '
    <p class="cover-module">' . docs_e($ctx['display_name']) . '</p>
    <h1>' . docs_e($title) . '</h1>
    ' . ($summary !== '' ? '<p class="cover-summary">' . docs_e($summary) . '</p>' : '') . '
  </div>
  <div class="cover-meta">
    <dl><dd>v' . docs_e($ctx['version']) . '</dd></dl>
    <dl><dd>' . docs_e($psRange) . '</dd></dl>
    <dl><dd><bdi>%%DOCS_DATE%%</bdi></dd></dl>
    ' . $author . '
  </div>
</section>
<nav class="sheet toc">
  <h2>' . docs_e($meta['toc_title'] ?? 'Contents') . '</h2>
  <ol>' . $toc . '</ol>
</nav>
<article class="sheet content">
' . $content . '
  <footer class="doc-footer"><span>' . docs_e($ctx['display_name'] . ' ' . $ctx['version']) . '</span><span>' . docs_e($ctx['module']) . '</span></footer>
</article>
</body>
</html>
';
}

