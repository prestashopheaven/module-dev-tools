/**
 * The build manifest (docs/build-manifest.json): what was generated from which input.
 *
 * @param array<string, mixed> $ctx
 *
 * @return array<string, mixed>
 */
function docs_build_manifest(array $ctx): array
{
    $manifest = docs_read_json($ctx['docs'] . '/build-manifest.json') ?? [];
    $manifest['_comment'] = 'Generated by ps-module docs. Do not edit.';
    $manifest += ['manual' => [], 'pdf' => [], 'warnings' => []];

    return $manifest;
}

/**
 * Values for the {{placeholders}} that manuals and marketing texts may use.
 *
 * @param array<string, mixed> $ctx
 *
 * @return array<string, string>
 */
function docs_placeholders(array $ctx): array
{
    return [
        'version' => (string) $ctx['version'],
        'display_name' => (string) $ctx['display_name'],
        'module_name' => (string) $ctx['module'],
        'ps_min' => (string) $ctx['ps_min'],
        'ps_tested' => (string) $ctx['ps_tested'],
        'php_min' => (string) $ctx['php_min'],
        'author' => (string) $ctx['author'],
    ];
}

/**
 * The context for one language: the display name translated as in the module's own translation
 * catalogue (<repo>/i18n/<iso>.json), so manuals and sheets use the same name as the shop.
 *
 * @param array<string, mixed> $ctx
 *
 * @return array<string, mixed>
 */
function docs_localize(array $ctx, string $iso): array
{
    $file = $ctx['repo'] . "/i18n/$iso.json";
    $catalogue = is_file($file) ? json_decode((string) file_get_contents($file), true) : null;
    foreach ((array) ($catalogue['strings'] ?? []) as $texts) {
        $translation = ((array) $texts)[(string) $ctx['display_name']] ?? null;
        $text = is_array($translation) ? (string) ($translation['text'] ?? '') : (string) $translation;
        if ($text !== '') {
            $ctx['display_name'] = $text;
            break;
        }
    }

    return $ctx;
}

/**
 * Replaces {{placeholders}} in a text.
 *
 * @param array<string, mixed> $ctx
 */
function docs_fill(array $ctx, string $text): string
{
    $values = docs_placeholders($ctx);

    return (string) preg_replace_callback('/\{\{\s*([a-z_]+)\s*\}\}/', static fn (array $m): string => $values[$m[1]] ?? $m[0], $text);
}

/**
 * The screenshot file of a language: its own, else the one of the shop language it fell back to, else the source language.
 *
 * @param array<string, mixed> $ctx
 */
function docs_screenshot_file(array $ctx, string $iso, string $id): ?string
{
    $manifest = docs_read_json($ctx['docs'] . '/screenshots/manifest.json') ?? [];
    $fallback = (string) ($manifest['languages'][$iso]['shop_language'] ?? $ctx['source']);
    foreach (array_unique([$iso, $fallback, $ctx['source']]) as $lang) {
        $file = $ctx['docs'] . "/screenshots/$lang/$id.png";
        if (is_file($file)) {
            return $file;
        }
    }

    return null;
}

/**
 * Relative path from one directory to a file (both absolute, forward slashes).
 */
function docs_relative_path(string $fromDir, string $file): string
{
    $from = explode('/', trim(str_replace('\\', '/', $fromDir), '/'));
    $to = explode('/', trim(str_replace('\\', '/', $file), '/'));
    while ($from !== [] && $to !== [] && strtolower($from[0]) === strtolower($to[0])) {
        array_shift($from);
        array_shift($to);
    }

    return str_repeat('../', count($from)) . implode('/', $to);
}

/**
 * A file as a data: URI (for the logo on the cover page).
 */
function docs_data_uri(string $file): string
{
    $type = str_ends_with(strtolower($file), '.svg') ? 'image/svg+xml' : (str_ends_with(strtolower($file), '.jpg') ? 'image/jpeg' : 'image/png');

    return "data:$type;base64," . base64_encode((string) file_get_contents($file));
}

/**
 * Font stack for a language, spelled out (CSS variables do not reach the @page margin boxes).
 */
function docs_font_stack(string $iso): string
{
    $script = match ($iso) {
        'ja' => '"Noto Sans CJK JP", "Yu Gothic UI", Meiryo, ',
        'zh' => '"Noto Sans CJK SC", "Microsoft YaHei", ',
        'ko' => '"Noto Sans CJK KR", "Malgun Gothic", ',
        'ar' => '"Noto Sans Arabic", ',
        'th' => '"Noto Sans Thai", "Leelawadee UI", ',
        default => '',
    };

    return $script . '"Noto Sans", "Segoe UI", Arial, sans-serif';
}

/**
 * Escapes text for HTML.
 */
function docs_e(string $text): string
{
    return htmlspecialchars($text, ENT_QUOTES, 'UTF-8');
}

