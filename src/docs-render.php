/**
 * The logo suggestions of the module: docs/content/logo-suggestions/*.svg (MKT-07: several, in the brand colours of
 * branding/brand.json), else the older single docs/content/logo-suggestion.svg.
 *
 * @param array<string, mixed> $ctx
 *
 * @return string[] paths of the SVG files, sorted
 */
function docs_logo_sources(array $ctx): array
{
    $files = glob($ctx['docs'] . '/content/logo-suggestions/*.svg') ?: [];
    sort($files);
    if ($files === [] && is_file($ctx['docs'] . '/content/logo-suggestion.svg')) {
        $files = [$ctx['docs'] . '/content/logo-suggestion.svg'];
    }

    return $files;
}

/**
 * Copies the logo suggestions to docs/marketing/logo-suggestions/ and renders a 512 px PNG of each (in Docker).
 *
 * @param array<string, mixed> $ctx
 *
 * @return list<array{svg: string, png: string}>
 */
function docs_render_logo(array $ctx): array
{
    $dir = $ctx['docs'] . '/marketing/logo-suggestions';
    $sources = docs_logo_sources($ctx);
    // Older builds wrote one logo-suggestion.svg/png next to the marketing sheets.
    foreach (['svg', 'png'] as $ext) {
        @unlink($ctx['docs'] . "/marketing/logo-suggestion.$ext");
    }
    if ($sources === []) {
        return [];
    }
    @mkdir($dir, 0775, true);
    $keep = [];
    $items = [];
    $logos = [];
    foreach ($sources as $source) {
        $name = pathinfo($source, PATHINFO_FILENAME);
        $svg = "$dir/$name.svg";
        $png = "$dir/$name.png";
        $keep[] = $svg;
        $keep[] = $png;
        $changed = !is_file($svg) || sha1_file($svg) !== sha1_file($source);
        copy($source, $svg);
        ps_vlog("logo suggestion $name: " . ($changed || !is_file($png) ? 'PNG to render' : 'unchanged, PNG kept') . " ($svg)");
        if ($changed || !is_file($png)) {
            $items[] = ['in' => docs_container_path($ctx, $svg), 'out' => docs_container_path($ctx, $png), 'size' => 512];
        }
        $logos[] = ['svg' => $svg, 'png' => $png];
    }
    foreach (glob("$dir/*") ?: [] as $old) {
        if (!in_array($old, $keep, true)) {
            unlink($old);
        }
    }
    if ($items !== [] && docs_docker_available() === '' && docs_ensure_image()['error'] === '') {
        docs_run_container($ctx, [['type' => 'svg-png', 'items' => $items]], null);
    } elseif ($items !== []) {
        ps_vlog('logo suggestions: PNGs not rendered (needs Docker and the docs image); the sheets show the SVG');
    }

    return array_map(static fn (array $l): array => ['svg' => $l['svg'], 'png' => is_file($l['png']) ? $l['png'] : ''], $logos);
}

/**
 * Builds the merged marketing data of a language: the Addons question, the value and its length per field.
 *
 * @param array<string, mixed> $ctx
 * @param array<string, mixed> $data
 *
 * @return array<string, array{question: string, value: mixed, scope: string, type: string, length: int, limit: string}>
 */
function docs_marketing_values(array $ctx, array $data): array
{
    $common = (array) ($ctx['config']['marketing'] ?? []);
    $values = [];
    foreach (docs_marketing_fields() as $key => $field) {
        $value = $field['scope'] === 'common' ? ($common[$key] ?? null) : ($data[$key] ?? null);
        if (is_string($value)) {
            $value = docs_fill($ctx, $value);
        } elseif (is_array($value)) {
            $value = array_map(static fn ($v) => is_string($v) ? docs_fill($ctx, $v) : $v, $value);
        }
        $length = is_string($value) ? mb_strlen(docs_plain_text($value)) : (is_array($value) ? (int) array_sum(array_map(static fn ($v): int => mb_strlen(docs_plain_text((string) $v)), $value)) : 0);
        $limit = isset($field['max']) && $field['type'] !== 'price' ? (string) $field['max'] : '';
        $values[$key] = ['question' => (string) $field['question'], 'value' => $value, 'scope' => (string) $field['scope'], 'type' => (string) $field['type'], 'length' => $length, 'limit' => $limit, 'internal' => !empty($field['internal'])];
    }

    return $values;
}

/**
 * Writes docs/marketing/<iso>/marketing.{json,md,html}; returns the HTML file.
 *
 * @param array<string, mixed> $ctx
 * @param array<string, mixed> $data
 * @param list<array{svg: string, png: string}> $logo
 */
function docs_render_marketing(array $ctx, string $iso, array $data, array $logo): string
{
    $ctx = docs_localize($ctx, $iso);
    $dir = $ctx['docs'] . "/marketing/$iso";
    @mkdir($dir, 0775, true);
    $values = docs_marketing_values($ctx, $data);
    $name = (string) ($ctx['catalog'][$iso]['name'] ?? $iso);

    // JSON: machine-readable.
    $json = ['_comment' => 'Generated by ps-module docs from docs/content/' . $iso . '/marketing.json and docs/docs.json. Do not edit.', 'module' => $ctx['module'], 'display_name' => $ctx['display_name'], 'version' => $ctx['version'], 'language' => $iso, 'fields' => []];
    foreach ($values as $key => $v) {
        $json['fields'][$key] = ['question' => $v['question'], 'value' => $v['value']];
    }
    docs_write_json("$dir/marketing.json", $json);

    // Markdown: to copy and paste.
    $md = "# {$ctx['display_name']} {$ctx['version']} – Addons product sheet ($name)\n";
    $n = 0;
    foreach ($values as $v) {
        $md .= "\n## " . ($v['internal'] ? '' : ++$n . '. ') . $v['question'] . "\n\n" . docs_marketing_text($v) . "\n";
    }
    file_put_contents("$dir/marketing.md", $md);

    // HTML: a sheet to review and copy from, field by field.
    $dirAttr = docs_is_rtl($ctx, $iso) ? 'rtl' : 'ltr';
    $cards = '';
    $n = 0;
    foreach ($values as $key => $v) {
        $number = $v['internal'] ? '·' : (string) ++$n;
        $cards .= '<section class="field' . ($v['internal'] ? ' internal' : '') . '" id="' . docs_e($key) . '">'
            . '<header><span class="num">' . $number . '</span><h2>' . docs_e($v['question']) . '</h2>'
            . ($v['scope'] === 'common' ? '<span class="tag">all languages</span>' : '')
            . '<button type="button" class="copy" data-target="v-' . docs_e($key) . '">Copy</button></header>'
            . '<div class="value" lang="' . ($v['scope'] === 'common' ? 'en' : docs_e($iso)) . '" dir="' . ($v['scope'] === 'common' ? 'ltr' : $dirAttr) . '">' . docs_marketing_value_html($v, $key === 'logo_suggestion' ? $logo : null, $dir) . '</div>'
            . '<textarea hidden id="v-' . docs_e($key) . '">' . docs_e(docs_marketing_text($v)) . '</textarea>'
            . '<footer>' . ($v['length'] > 0 ? $v['length'] . ($v['limit'] !== '' ? ' / ' . $v['limit'] : '') . ' characters' : '') . '</footer>'
            . "</section>\n";
    }
    $images = '';
    foreach ((array) ($ctx['config']['screenshots'] ?? []) as $shot) {
        $id = (string) ($shot['id'] ?? '');
        if (!empty($shot['languages']) && !in_array($iso, (array) $shot['languages'], true)) {
            continue;
        }
        $file = docs_framed_file($ctx, $iso, $id);
        $file = $file !== '' ? $file : (string) docs_screenshot_file($ctx, $iso, $id);
        if ($file !== '') {
            $rel = docs_relative_path($dir, $file);
            $size = @getimagesize($file) ?: [0, 0];
            $images .= '<figure><a href="' . docs_e($rel) . '" download><img src="' . docs_e($rel) . '" alt="" loading="lazy"></a><figcaption><b>' . docs_e($id) . '</b> ' . $size[0] . ' x ' . $size[1] . ' px</figcaption></figure>';
        }
    }
    if ($images !== '') {
        $cards .= '<section class="field" id="images"><header><span class="num">·</span><h2>Product images (screenshots)</h2></header><div class="value gallery">' . $images . "</div><footer>Upload these in this order; click an image to download it.</footer></section>\n";
    }
    $css = (string) file_get_contents(DOCS_RESOURCES . '/docs/marketing.css');
    $languageLinks = '';
    foreach ($ctx['languages'] as $lang) {
        $languageLinks .= '<a href="../' . docs_e($lang) . '/marketing.html"' . ($lang === $iso ? ' aria-current="page"' : '') . '>' . docs_e($lang) . '</a>';
    }
    $html = '<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<meta name="generator" content="ps-module docs">
<title>' . docs_e($ctx['display_name'] . ' – Addons sheet (' . $iso . ')') . '</title>
<style>' . $css . '</style>
</head>
<body>
<header class="top">
  <div>
    <p class="eyebrow">Addons product sheet · ' . docs_e($name) . '</p>
    <h1>' . docs_e($ctx['display_name']) . ' <span>' . docs_e($ctx['version']) . '</span></h1>
    <p class="sub"><code>' . docs_e($ctx['module']) . '</code> · generated from <code>docs/content/' . docs_e($iso) . '/marketing.json</code> and <code>docs/docs.json</code></p>
  </div>
  <nav class="langs">' . $languageLinks . '</nav>
</header>
<main>
' . $cards . '</main>
<script>
document.querySelectorAll("button.copy").forEach(function (b) {
  b.addEventListener("click", function () {
    var t = document.getElementById(b.dataset.target).value;
    var done = function () { b.textContent = "Copied"; setTimeout(function () { b.textContent = "Copy"; }, 1500); };
    if (navigator.clipboard) { navigator.clipboard.writeText(t).then(done, done); } else { done(); }
  });
});
</script>
</body>
</html>
';
    file_put_contents("$dir/marketing.html", $html);
    ps_vlog("marketing $iso: wrote $dir/marketing.json, marketing.md, marketing.html");

    return "$dir/marketing.html";
}

/**
 * Plain text of a marketing value, as it is pasted into the Addons form.
 *
 * @param array{value: mixed, type: string} $v
 */
function docs_marketing_text(array $v): string
{
    $value = $v['value'];
    if ($v['type'] === 'price' && (is_int($value) || is_float($value))) {
        // 0 = a free module (sold or given away outside Addons, e.g. the PrestaHaven Updater).
        return (float) $value == 0.0 ? 'Free' : number_format((float) $value, 2, '.', '');
    }
    if (is_array($value)) {
        return $value === [] ? '-' : implode("\n", array_map(static fn ($item): string => '- ' . $item, $value));
    }

    return trim((string) $value);
}

/**
 * HTML of a marketing value (lists as lists, Markdown for the installation instructions, the logo image).
 *
 * @param array{value: mixed, type: string} $v
 * @param list<array{svg: string, png: string}>|null $logo
 */
function docs_marketing_value_html(array $v, ?array $logo, string $dir): string
{
    $value = $v['value'];
    $noImages = static fn (): ?array => null;
    if ($v['type'] === 'price') {
        $text = docs_marketing_text($v);

        return '<p class="big">' . ($text === 'Free' ? '' : '€ ') . docs_e($text) . '</p>';
    }
    if (is_array($value)) {
        if ($value === []) {
            return '<p class="none">None</p>';
        }

        return ($v['type'] === 'list' && str_contains(strtolower($v['question']), 'steps') ? '<ol>' : '<ul>')
            . implode('', array_map(static fn ($item): string => '<li>' . docs_md_inline((string) $item, $noImages) . '</li>', $value))
            . (str_contains(strtolower($v['question']), 'steps') ? '</ol>' : '</ul>');
    }
    $html = docs_md_render((string) $value, $noImages);
    foreach (array_reverse($logo ?? []) as $index => $one) {
        $html = '<figure class="logo"><img src="' . docs_e(docs_relative_path($dir, $one['png'] !== '' ? $one['png'] : $one['svg'])) . '" alt="Logo suggestion ' . (count($logo ?? []) - $index) . '"></figure>' . $html;
    }

    return $html;
}

