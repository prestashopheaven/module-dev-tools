/**
 * The PDF engines to try, in order.
 *
 * @param array<string, mixed> $ctx
 *
 * @return string[]
 */
function docs_pdf_engines(array $ctx): array
{
    $engines = (array) ($ctx['config']['pdf']['engines'] ?? ['docker', 'chrome', 'wkhtmltopdf', 'dompdf']);

    return array_values(array_intersect(array_map('strval', $engines), ['docker', 'chrome', 'wkhtmltopdf', 'dompdf']));
}

/**
 * Prints every manual to PDF with the first engine that works; skips PDFs whose input did not change.
 *
 * @param array<string, mixed> $ctx
 * @param array<string, string> $htmlFiles iso => manual.html
 * @param array<string, mixed> $manifest updated with the PDF state per language
 *
 * @return array<string, array{ok: bool, engine: string, error: string, file: string, up_to_date: bool, warnings: string[]}>
 */
function docs_render_pdfs(array $ctx, array $htmlFiles, array &$manifest): array
{
    $results = [];
    $todo = [];
    foreach ($htmlFiles as $iso => $html) {
        $pdf = dirname($html) . "/readme_$iso.pdf";
        $hash = docs_pdf_input_hash($html);
        $previous = $manifest['pdf'][$iso] ?? [];
        if (is_file($pdf) && ($previous['hash'] ?? '') === $hash && !empty($previous['ok'])) {
            ps_vlog("PDF $iso: up to date, skipped (same input as the last build, made by " . ($previous['engine'] ?? '?') . ')');
            $results[$iso] = ['ok' => true, 'engine' => (string) $previous['engine'], 'error' => '', 'file' => $pdf, 'up_to_date' => true, 'warnings' => (array) ($previous['warnings'] ?? [])];
            continue;
        }
        ps_vlog("PDF $iso: to make (" . (!is_file($pdf) ? 'no PDF yet' : (empty($previous['ok']) ? 'the last attempt failed' : 'the HTML or its images changed')) . ')');
        $todo[$iso] = ['html' => $html, 'pdf' => $pdf, 'hash' => $hash];
    }
    $reasons = [];
    ps_vlog('PDF engines in order: ' . implode(' > ', docs_pdf_engines($ctx)) . (isset($ctx['config']['pdf']['engines']) ? ' (docs.json > pdf.engines)' : ' (default)'));
    foreach (docs_pdf_engines($ctx) as $engine) {
        if ($todo === []) {
            break;
        }
        ps_vlog("PDF engine $engine: trying for " . implode(', ', array_keys($todo)));
        $start = microtime(true);
        $done = match ($engine) {
            'docker' => docs_pdf_docker($ctx, $todo),
            'chrome' => docs_pdf_chrome($todo),
            'wkhtmltopdf' => docs_pdf_wkhtmltopdf($todo),
            'dompdf' => docs_pdf_dompdf($ctx, $todo),
            default => ['error' => 'unknown engine'],
        };
        if (isset($done['error'])) {
            $reasons[] = "$engine: " . $done['error'];
            ps_vlog("PDF engine $engine: not usable, next engine (" . $done['error'] . ')');
            continue;
        }
        ps_vdone("PDF engine $engine", $start);
        foreach ($done as $iso => $state) {
            ps_vlog("PDF $iso via $engine: " . ($state['ok'] ? 'ok, ' . $todo[$iso]['pdf'] : 'failed (' . $state['error'] . '), next engine'));
            if ($state['ok']) {
                $results[$iso] = ['ok' => true, 'engine' => $engine, 'error' => '', 'file' => $todo[$iso]['pdf'], 'up_to_date' => false, 'warnings' => $state['warnings'] ?? []];
                $manifest['pdf'][$iso] = ['hash' => $todo[$iso]['hash'], 'engine' => $engine, 'ok' => true, 'warnings' => $state['warnings'] ?? []];
                unset($todo[$iso]);
            } else {
                $reasons[] = "$engine ($iso): " . $state['error'];
            }
        }
    }
    foreach ($todo as $iso => $item) {
        $results[$iso] = ['ok' => false, 'engine' => '', 'error' => $reasons === [] ? 'no PDF engine configured' : implode('; ', array_unique($reasons)), 'file' => $item['pdf'], 'up_to_date' => false, 'warnings' => []];
        $manifest['pdf'][$iso] = ['hash' => '', 'engine' => '', 'ok' => false, 'error' => $results[$iso]['error']];
    }
    ksort($results);

    return $results;
}

/**
 * Hash of everything a PDF is made from: the HTML and the images it references.
 */
function docs_pdf_input_hash(string $htmlFile): string
{
    $html = (string) file_get_contents($htmlFile);
    $hash = hash_init('sha1');
    hash_update($hash, $html);
    preg_match_all('/<img[^>]+src="([^"]+)"/', $html, $m);
    foreach ($m[1] as $src) {
        $file = dirname($htmlFile) . '/' . html_entity_decode($src);
        if (!str_starts_with($src, 'data:') && is_file($file)) {
            hash_update($hash, (string) sha1_file($file));
        }
    }

    return hash_final($hash);
}

/**
 * Prints the PDF result per language; returns true when every PDF exists.
 *
 * @param array<string, mixed> $ctx
 * @param array<string, array{ok: bool, engine: string, error: string, file: string, up_to_date: bool, warnings: string[]}> $pdfs
 */
function docs_print_pdf_results(array $ctx, array $pdfs): bool
{
    $ok = true;
    foreach ($pdfs as $iso => $pdf) {
        if ($pdf['ok']) {
            echo "  $iso  " . docs_rel($ctx, $pdf['file']) . ' (' . ($pdf['up_to_date'] ? 'up to date' : $pdf['engine'] . ', ' . round(filesize($pdf['file']) / 1024) . ' KB') . ")\n";
            foreach ($pdf['warnings'] as $warning) {
                echo "       warning: $warning\n";
            }
        } else {
            $ok = false;
            echo "  $iso  PDF NOT generated: {$pdf['error']}\n";
            echo '       The print-ready HTML is ' . docs_rel($ctx, dirname($pdf['file']) . '/manual.html') . " (open it in a browser, Print, Save as PDF).\n";
        }
    }

    return $ok;
}

/**
 * Engine "docker": Chromium with Noto fonts in the docs-tools image; checks the embedded fonts with pdffonts.
 *
 * @param array<string, mixed> $ctx
 * @param array<string, array{html: string, pdf: string, hash: string}> $todo
 *
 * @return array<string, array{ok: bool, error: string, warnings?: string[]}>|array{error: string}
 */
function docs_pdf_docker(array $ctx, array $todo): array
{
    $problem = docs_docker_available();
    if ($problem !== '') {
        return ['error' => $problem];
    }
    $image = docs_ensure_image();
    if ($image['error'] !== '') {
        return ['error' => $image['error']];
    }
    $items = [];
    foreach ($todo as $item) {
        $items[] = ['html' => docs_container_path($ctx, $item['html']), 'out' => docs_container_path($ctx, $item['pdf'])];
    }
    $run = docs_run_container($ctx, [['type' => 'pdf', 'items' => $items]], null);
    if ($run['error'] !== '') {
        return ['error' => $run['error']];
    }
    $byOut = [];
    foreach ($run['results'] as $result) {
        $byOut[$result['out'] ?? ''] = $result;
    }
    $fonts = docs_pdf_fonts($ctx, array_column($todo, 'pdf'));
    $states = [];
    foreach ($todo as $iso => $item) {
        $result = $byOut[docs_container_path($ctx, $item['pdf'])] ?? ['ok' => false, 'error' => 'no result'];
        $ok = !empty($result['ok']) && docs_is_pdf($item['pdf']);
        $warnings = [];
        if ($ok) {
            $expected = docs_expected_font($iso);
            $used = $fonts[$item['pdf']] ?? '';
            if ($used !== '' && $expected !== '' && stripos($used, $expected) === false) {
                $warnings[] = "expected the font $expected for this language, the PDF embeds: $used (check the glyphs: ps-module docs preview $iso)";
            }
        }
        $states[$iso] = ['ok' => $ok, 'error' => $ok ? '' : (string) ($result['error'] ?? 'failed'), 'warnings' => $warnings];
    }

    return $states;
}

/**
 * The Noto font a PDF of a language must embed (by script); '' for Latin, Cyrillic and Greek.
 */
function docs_expected_font(string $iso): string
{
    return match ($iso) {
        'ja', 'zh', 'ko' => 'CJK',
        'ar' => 'Arabic',
        'th' => 'Thai',
        default => '',
    };
}

/**
 * The fonts embedded in PDFs (pdffonts in the docs-tools image): file => comma-separated font names.
 *
 * @param array<string, mixed> $ctx
 * @param string[] $pdfs
 *
 * @return array<string, string>
 */
function docs_pdf_fonts(array $ctx, array $pdfs): array
{
    $script = '';
    foreach ($pdfs as $pdf) {
        $script .= 'echo "@@ ' . docs_container_path($ctx, $pdf) . '"; pdffonts "' . docs_container_path($ctx, $pdf) . '" 2>/dev/null; ';
    }
    [$code, $output] = docs_exec(array_merge(['docker', 'run', '--rm'], docs_mount_args($ctx, null), [docs_image_tag(), 'sh', '-c', $script]), 300);
    if ($code !== 0) {
        return [];
    }
    $fonts = [];
    $current = '';
    foreach (explode("\n", $output) as $line) {
        if (str_starts_with($line, '@@ ')) {
            $current = trim(substr($line, 3));
            $fonts[$current] = [];
        } elseif ($current !== '' && preg_match('/^(?:[A-Z]{6}\+)?(\S+)\s+(Type|TrueType|CID)/', $line, $m)) {
            $fonts[$current][$m[1]] = true;
        }
    }
    $byFile = [];
    foreach ($pdfs as $pdf) {
        $byFile[$pdf] = implode(', ', array_keys($fonts[docs_container_path($ctx, $pdf)] ?? []));
        ps_vlog("fonts in $pdf: " . ($byFile[$pdf] !== '' ? $byFile[$pdf] : '(none found)'));
    }

    return $byFile;
}

/**
 * True when a file exists and starts like a PDF.
 */
function docs_is_pdf(string $file): bool
{
    clearstatcache(true, $file);

    return is_file($file) && filesize($file) > 1000 && (string) file_get_contents($file, false, null, 0, 5) === '%PDF-';
}

/**
 * Engine "chrome": a local Chrome, Edge or Chromium in headless mode.
 *
 * @param array<string, array{html: string, pdf: string, hash: string}> $todo
 *
 * @return array<string, array{ok: bool, error: string}>|array{error: string}
 */
function docs_pdf_chrome(array $todo): array
{
    $chrome = docs_find_chrome();
    if ($chrome === null) {
        return ['error' => 'no local Chrome, Edge or Chromium found (set PS_DOCS_CHROME to its path)'];
    }
    $states = [];
    foreach ($todo as $iso => $item) {
        $profile = sys_get_temp_dir() . '/ps-docs-chrome-' . uniqid();
        @unlink($item['pdf']);
        ps_vlog("PDF $iso (chrome): {$item['html']} -> {$item['pdf']}");
        [$code, $output] = docs_exec([
            $chrome, '--headless=new', '--disable-gpu', '--no-first-run', '--no-default-browser-check', '--disable-extensions',
            '--user-data-dir=' . $profile, '--no-pdf-header-footer', '--virtual-time-budget=15000',
            '--print-to-pdf=' . $item['pdf'], docs_file_url($item['html']),
        ], 180);
        docs_remove_dir($profile);
        $ok = docs_is_pdf($item['pdf']);
        $states[$iso] = ['ok' => $ok, 'error' => $ok ? '' : 'exit code ' . $code . ': ' . substr(trim($output), 0, 200)];
    }

    return $states;
}

/**
 * Engine "wkhtmltopdf".
 *
 * @param array<string, array{html: string, pdf: string, hash: string}> $todo
 *
 * @return array<string, array{ok: bool, error: string}>|array{error: string}
 */
function docs_pdf_wkhtmltopdf(array $todo): array
{
    $bin = docs_find_executable('wkhtmltopdf');
    if ($bin === null) {
        return ['error' => 'wkhtmltopdf is not installed'];
    }
    $states = [];
    foreach ($todo as $iso => $item) {
        [$code, $output] = docs_exec([$bin, '--quiet', '--enable-local-file-access', '--print-media-type', '--encoding', 'utf-8', $item['html'], $item['pdf']], 180);
        $ok = docs_is_pdf($item['pdf']);
        $states[$iso] = ['ok' => $ok, 'error' => $ok ? '' : 'exit code ' . $code . ': ' . substr(trim($output), 0, 200)];
    }

    return $states;
}

/**
 * True when dompdf can be loaded (from the module's vendor directory or this package's).
 *
 * @param array<string, mixed> $ctx
 */
function docs_dompdf_available(array $ctx): bool
{
    if (!class_exists('Dompdf\Dompdf')) {
        foreach ([$ctx['module_dir'] . '/vendor/autoload.php', __DIR__ . '/../vendor/autoload.php'] as $autoload) {
            if (is_file($autoload)) {
                require_once $autoload;
                if (class_exists('Dompdf\Dompdf')) {
                    ps_vlog("dompdf: loaded through $autoload");
                    break;
                }
            }
        }
    }
    if (!class_exists('Dompdf\Dompdf')) {
        ps_vlog('dompdf: not installed (not in the module vendor/ nor in this package)');
    }

    return class_exists('Dompdf\Dompdf');
}

/**
 * Engine "dompdf": pure PHP, only for scripts its DejaVu fonts cover (no Arabic shaping, no CJK, no Thai).
 *
 * @param array<string, mixed> $ctx
 * @param array<string, array{html: string, pdf: string, hash: string}> $todo
 *
 * @return array<string, array{ok: bool, error: string}>|array{error: string}
 */
function docs_pdf_dompdf(array $ctx, array $todo): array
{
    if (!docs_dompdf_available($ctx)) {
        return ['error' => 'dompdf is not installed (composer require --dev dompdf/dompdf)'];
    }
    $states = [];
    foreach ($todo as $iso => $item) {
        if (docs_expected_font($iso) !== '' || docs_is_rtl($ctx, $iso)) {
            $states[$iso] = ['ok' => false, 'error' => 'dompdf cannot render this script (no shaping/right-to-left/CJK support)'];
            continue;
        }
        $start = microtime(true);
        try {
            $class = 'Dompdf\Dompdf';
            $dompdf = new $class(['isRemoteEnabled' => false, 'chroot' => $ctx['docs'], 'defaultFont' => 'DejaVu Sans']);
            $html = (string) file_get_contents($item['html']);
            // dompdf does not know CSS variables in shorthand values and page-margin boxes: use plain fonts.
            $html = str_replace('</style>', 'body,h1,h2,h3,p,li,td,th{font-family:"DejaVu Sans",sans-serif}</style>', $html);
            $dompdf->setBasePath(dirname($item['html']));
            $dompdf->loadHtml($html, 'UTF-8');
            $dompdf->setPaper('A4');
            $dompdf->render();
            file_put_contents($item['pdf'], $dompdf->output());
            ps_vdone("dompdf $iso: {$item['pdf']}", $start);
            $ok = docs_is_pdf($item['pdf']);
            $states[$iso] = ['ok' => $ok, 'error' => $ok ? '' : 'no output'];
        } catch (Throwable $e) {
            $states[$iso] = ['ok' => false, 'error' => $e->getMessage()];
        }
    }

    return $states;
}

/**
 * Finds a local Chrome, Edge or Chromium (PS_DOCS_CHROME overrides).
 */
function docs_find_chrome(): ?string
{
    static $found = false;
    if ($found !== false) {
        return $found;
    }
    $env = getenv('PS_DOCS_CHROME');
    if (is_string($env) && $env !== '' && is_file($env)) {
        ps_vlog("Chrome/Edge: $env (PS_DOCS_CHROME)");

        return $found = $env;
    }
    if (is_string($env) && $env !== '') {
        ps_vlog("PS_DOCS_CHROME is set to $env, but that file does not exist: searching");
    }
    $candidates = [];
    if (PHP_OS_FAMILY === 'Windows') {
        foreach (['ProgramFiles', 'ProgramFiles(x86)', 'LOCALAPPDATA'] as $var) {
            $base = getenv($var);
            if (is_string($base) && $base !== '') {
                $candidates[] = "$base\\Google\\Chrome\\Application\\chrome.exe";
                $candidates[] = "$base\\Microsoft\\Edge\\Application\\msedge.exe";
                $candidates[] = "$base\\Chromium\\Application\\chrome.exe";
            }
        }
    } elseif (PHP_OS_FAMILY === 'Darwin') {
        $candidates = ['/Applications/Google Chrome.app/Contents/MacOS/Google Chrome', '/Applications/Microsoft Edge.app/Contents/MacOS/Microsoft Edge', '/Applications/Chromium.app/Contents/MacOS/Chromium'];
    }
    foreach ($candidates as $candidate) {
        if (is_file($candidate)) {
            ps_vlog("Chrome/Edge: $candidate");

            return $found = $candidate;
        }
    }
    foreach (['google-chrome', 'google-chrome-stable', 'chromium', 'chromium-browser', 'microsoft-edge', 'microsoft-edge-stable'] as $name) {
        $path = docs_find_executable($name);
        if ($path !== null) {
            ps_vlog("Chrome/Edge: $path (on the PATH)");

            return $found = $path;
        }
    }
    ps_vlog('Chrome/Edge: not found (looked in: ' . ($candidates === [] ? 'the PATH' : implode(', ', $candidates) . ' and the PATH') . ')');

    return $found = null;
}

/**
 * Finds an executable on the PATH.
 */
function docs_find_executable(string $name): ?string
{
    $exts = PHP_OS_FAMILY === 'Windows' ? ['.exe', '.cmd', '.bat', ''] : [''];
    foreach (explode(PATH_SEPARATOR, (string) getenv('PATH')) as $dir) {
        foreach ($exts as $ext) {
            $file = rtrim($dir, '/\\') . DIRECTORY_SEPARATOR . $name . $ext;
            if ($dir !== '' && is_file($file)) {
                ps_vlog("$name: $file");

                return $file;
            }
        }
    }
    ps_vlog("$name: not on the PATH");

    return null;
}

/**
 * A file:// URL for a local file.
 */
function docs_file_url(string $file): string
{
    $path = str_replace('\\', '/', $file);
    $encoded = implode('/', array_map('rawurlencode', explode('/', $path)));
    $encoded = (string) preg_replace('#^([A-Za-z])%3A#', '$1:', $encoded);

    return 'file://' . (str_starts_with($encoded, '/') ? '' : '/') . $encoded;
}

/**
 * Renders pages of a manual PDF to PNG files in .cache/docs/preview/ (pdftoppm in the docs-tools image).
 *
 * @param array<string, mixed> $ctx
 *
 * @return array{ok: bool, message: string}
 */
function docs_pdf_preview(array $ctx, string $iso, string $pages): array
{
    $pdf = $ctx['docs'] . "/manual/$iso/readme_$iso.pdf";
    if (!is_file($pdf)) {
        return ['ok' => false, 'message' => 'No PDF for ' . $iso . ' yet (' . docs_rel($ctx, $pdf) . '): run ps-module docs build or docs manual ' . $iso];
    }
    $problem = docs_docker_available();
    if ($problem !== '') {
        return ['ok' => false, 'message' => "Preview needs Docker ($problem). Open the PDF itself: " . docs_rel($ctx, $pdf)];
    }
    $image = docs_ensure_image();
    if ($image['error'] !== '') {
        return ['ok' => false, 'message' => $image['error']];
    }
    [$first, $last] = array_map('intval', explode('-', $pages . '-' . $pages)) + [1, 3];
    $outDir = $ctx['repo'] . '/.cache/docs/preview';
    ps_vlog("preview: $pdf, pages $first-$last, into $outDir");
    @mkdir($outDir, 0775, true);
    foreach (glob("$outDir/$iso-*.png") ?: [] as $old) {
        @unlink($old);
    }
    [$code, $output] = docs_exec(array_merge(['docker', 'run', '--rm'], docs_mount_args($ctx, null), [
        docs_image_tag(), 'pdftoppm', '-png', '-r', '70', '-f', (string) $first, '-l', (string) $last,
        docs_container_path($ctx, $pdf), '/cache/preview/' . $iso,
    ]), 300);
    $files = glob("$outDir/$iso-*.png") ?: [];
    if ($code !== 0 || $files === []) {
        return ['ok' => false, 'message' => 'pdftoppm failed: ' . trim($output)];
    }

    return ['ok' => true, 'message' => "Preview of the $iso PDF (pages $first-$last):\n  " . implode("\n  ", array_map(static fn (string $f): string => str_replace('\\', '/', $f), $files))];
}

