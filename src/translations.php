/**
 * Scans the module and returns its texts per domain, texts in core domains and problems.
 *
 * Module texts: domain "Modules.<Module>.<Part>" -> English text -> references ("file:line").
 * Core texts (Admin.*, Shop.*, ...): translated by PrestaShop itself, only checked for existence.
 *
 * @param array<string, mixed> $ctx
 *
 * @return array{strings: array<string, array<string, string[]>>, core: array<string, array<string, string[]>>, problems: array<int, array{level: string, ref: string, message: string}>}
 */
function tr_extract(array $ctx): array
{
    $strings = [];
    $core = [];
    $problems = [];
    $domainPattern = '/^' . preg_quote($ctx['prefix'], '/') . '[A-Z][A-Za-z0-9]*$/';
    $sourceFiles = tr_source_files($ctx['moduleDir']);
    $types = array_count_values(array_map(static fn (string $f): string => pathinfo($f, PATHINFO_EXTENSION), $sourceFiles));
    ps_vlog('translations: scanning ' . count($sourceFiles) . ' file(s) (' . implode(', ', array_map(static fn (string $t, int $n): string => "$n .$t", array_keys($types), $types))
        . '; skipped folders: ' . implode(', ', TR_SKIP_DIRS) . ')');
    foreach ($sourceFiles as $relative) {
        $code = (string) file_get_contents($ctx['moduleDir'] . '/' . $relative);
        if (str_ends_with($relative, '.php')) {
            $found = tr_extract_php($code, $ctx['adminDomain']);
        } elseif (str_ends_with($relative, '.tpl')) {
            $found = tr_extract_smarty($code);
        } else {
            $found = tr_extract_twig($code);
        }
        foreach ($found['problems'] as [$level, $line, $message]) {
            $problems[] = ['level' => $level, 'ref' => "$relative:$line", 'message' => $message];
        }
        foreach ($found['entries'] as [$source, $domain, $line]) {
            $ref = "$relative:$line";
            if (trim($source) === '') {
                $problems[] = ['level' => 'error', 'ref' => $ref, 'message' => 'Empty text.'];
            } elseif (preg_match('/[\x00-\x08\x0B\x0C\x0E-\x1F]/', $source)) {
                $problems[] = ['level' => 'error', 'ref' => $ref, 'message' => 'Text contains control characters (not allowed in XLF).'];
            } elseif (preg_match($domainPattern, $domain)) {
                $strings[$domain][$source][] = $ref;
            } elseif (str_starts_with($domain, 'Modules.')) {
                $problems[] = ['level' => 'error', 'ref' => $ref, 'message' => "Domain '$domain' does not belong to this module: use '{$ctx['prefix']}Admin', '{$ctx['prefix']}Shop' or '{$ctx['prefix']}Emails' (TR-02)."];
            } else {
                $core[$domain][$source][] = $ref;
            }
        }
    }
    ksort($strings, SORT_STRING);
    foreach ($strings as &$sources) {
        ksort($sources, SORT_STRING);
    }
    unset($sources);
    ksort($core, SORT_STRING);
    $problems = array_merge($problems, tr_check_core($ctx, $core));
    foreach ($strings as $domain => $sources) {
        ps_vlog("translations: $domain: " . count($sources) . ' text(s)');
    }
    ps_vlog('translations: ' . array_sum(array_map('count', $core)) . ' text(s) in ' . count($core) . ' core domain(s) (translated by PrestaShop), '
        . count($problems) . ' source problem(s)');

    return ['strings' => $strings, 'core' => $core, 'problems' => $problems];
}

/**
 * Warns about texts in core domains that PrestaShop does not have: those stay English.
 * Checked against the default catalogues of the PrestaShop versions in tests/phpstan/config.json.
 *
 * @param array<string, mixed> $ctx
 * @param array<string, array<string, string[]>> $core
 *
 * @return array<int, array{level: string, ref: string, message: string}>
 */
function tr_check_core(array $ctx, array $core): array
{
    $config = tr_read_json($ctx['moduleDir'] . '/tests/phpstan/config.json');
    $dirs = [];
    foreach ((array) ($config['versions'] ?? []) as $version) {
        $dir = rtrim((string) ($config['cache_dir'] ?? ''), '/') . '/' . $version . '/translations/default';
        if (is_dir($dir)) {
            $dirs[(string) $version] = $dir;
        }
    }
    if ($dirs === []) {
        ps_vlog('translations: core texts not checked (no PrestaShop catalogues in the cache_dir of tests/phpstan/config.json)');

        return [];
    }
    ps_vlog('translations: core texts checked against PrestaShop ' . implode(', ', array_keys($dirs)) . ' (' . implode(', ', $dirs) . ')');
    $problems = [];
    foreach ($core as $domain => $sources) {
        $known = [];
        $domainExists = false;
        foreach ($dirs as $dir) {
            $file = $dir . '/' . str_replace('.', '', $domain) . '.xlf';
            if (is_file($file)) {
                $domainExists = true;
                preg_match_all('#<source>(.*?)</source>#s', (string) file_get_contents($file), $m);
                foreach ($m[1] as $text) {
                    $known[html_entity_decode($text, ENT_QUOTES | ENT_XML1, 'UTF-8')] = true;
                }
            }
        }
        foreach ($sources as $source => $refs) {
            if (!isset($known[$source])) {
                $why = $domainExists ? "is not a PrestaShop text in '$domain'" : "uses the unknown domain '$domain'";
                $problems[] = ['level' => 'warning', 'ref' => $refs[0], 'message' => "'$source' $why (checked: " . implode(', ', array_keys($dirs)) . "), so it stays English. Use '{$ctx['adminDomain']}' or '{$ctx['prefix']}Shop'."];
            }
        }
    }

    return $problems;
}

/**
 * Extracts trans() calls, ['key' => ..., 'domain' => ...] arrays, tab wordings and choice labels from PHP code,
 * following the rules of PrestaShop's own PHP extractor (literal texts and domains only).
 *
 * @return array{entries: array<int, array{0: string, 1: string, 2: int}>, problems: array<int, array{0: string, 1: int, 2: string}>}
 */
function tr_extract_php(string $code, string $adminDomain): array
{
    try {
        $all = PhpToken::tokenize($code, TOKEN_PARSE);
    } catch (Throwable $e) {
        return ['entries' => [], 'problems' => [['error', $e->getLine(), 'PHP parse error: ' . $e->getMessage()]]];
    }
    // The marker covers the line of the comment (a trailing comment) and the whole next statement.
    $tokens = [];
    $ignored = [];
    $ignoredTokens = [];
    $inIgnoredStatement = false;
    foreach ($all as $token) {
        if ($token->is([T_COMMENT, T_DOC_COMMENT])) {
            if (str_contains($token->text, TR_IGNORE_MARKER)) {
                $ignored[$token->line] = true;
                $inIgnoredStatement = true;
            }
            continue;
        }
        if (!$token->isIgnorable()) {
            if ($inIgnoredStatement) {
                $ignoredTokens[count($tokens)] = true;
                $inIgnoredStatement = !in_array($token->text, [';', '{', '}'], true);
            }
            $tokens[] = $token;
        }
    }

    $entries = [];
    $problems = [];
    $count = count($tokens);
    for ($i = 1; $i < $count - 1; ++$i) {
        $token = $tokens[$i];
        $line = $token->line;
        $isIgnored = isset($ignored[$line]) || isset($ignoredTokens[$i]);

        // Method and static calls: ->trans(, ?->trans(, ::trans(, ->l(
        if ($token->id === T_STRING && in_array(strtolower($token->text), ['trans', 'l'], true)
            && $tokens[$i + 1]->text === '('
            && $tokens[$i - 1]->is([T_OBJECT_OPERATOR, T_NULLSAFE_OBJECT_OPERATOR, T_DOUBLE_COLON])) {
            if ($isIgnored) {
                continue;
            }
            if (strtolower($token->text) === 'l') {
                $problems[] = ['error', $line, "Legacy l(): the module uses the new translation system, so use \$this->trans('…', [], '$adminDomain') (TR-01)."];
                continue;
            }
            $call = tr_php_trans_call(tr_php_split($tokens, $i + 1));
            if ($call['error'] !== null) {
                $problems[] = ['error', $line, $call['error']];
            } else {
                $entries[] = [(string) $call['id'], (string) $call['domain'], $line];
            }
            continue;
        }

        // Array literals: [ ... ] (not an index access) and array( ... )
        $open = null;
        if ($token->text === '[' && !tr_php_is_index_access($tokens[$i - 1])) {
            $open = $i;
        } elseif ($token->id === T_ARRAY && $tokens[$i + 1]->text === '(') {
            $open = $i + 1;
        }
        if ($open !== null && !$isIgnored) {
            [$found, $warnings] = tr_php_array_entries(tr_php_array_items(tr_php_split($tokens, $open)), $tokens, $adminDomain);
            array_push($entries, ...$found);
            array_push($problems, ...$warnings);
        }
    }

    return ['entries' => $entries, 'problems' => $problems];
}

/**
 * True when a "[" after this token is an index access ($a['x'], f()[0]) rather than an array literal.
 */
function tr_php_is_index_access(PhpToken $previous): bool
{
    return in_array($previous->text, [']', ')', '}'], true)
        || $previous->is([T_VARIABLE, T_STRING, T_CONSTANT_ENCAPSED_STRING, T_NAME_QUALIFIED, T_NAME_FULLY_QUALIFIED, T_STATIC]);
}

/**
 * Splits the tokens between an opening bracket and its closing bracket into top-level arguments (or array items).
 *
 * @param PhpToken[] $tokens
 *
 * @return array<int, PhpToken[]>
 */
function tr_php_split(array $tokens, int $open): array
{
    $parts = [];
    $current = [];
    $depth = 0;
    $count = count($tokens);
    for ($j = $open; $j < $count; ++$j) {
        $token = $tokens[$j];
        if (in_array($token->text, ['(', '[', '{', '${'], true) || $token->is([T_CURLY_OPEN, T_DOLLAR_OPEN_CURLY_BRACES])) {
            if ($depth > 0) {
                $current[] = $token;
            }
            ++$depth;
            continue;
        }
        if (in_array($token->text, [')', ']', '}'], true)) {
            --$depth;
            if ($depth === 0) {
                if ($current !== []) {
                    $parts[] = $current;
                }

                return $parts;
            }
            $current[] = $token;
            continue;
        }
        if ($token->text === ',' && $depth === 1) {
            $parts[] = $current;
            $current = [];
            continue;
        }
        $current[] = $token;
    }

    return $parts;
}

/**
 * The decoded value of an argument that is exactly one string literal, otherwise null.
 *
 * @param PhpToken[] $arg
 */
function tr_php_literal(array $arg): ?string
{
    if (count($arg) !== 1 || $arg[0]->id !== T_CONSTANT_ENCAPSED_STRING) {
        return null;
    }

    return tr_php_string($arg[0]->text);
}

/**
 * Decodes a PHP string literal ('...' or "..." without interpolation) to its value.
 */
function tr_php_string(string $literal): string
{
    if ($literal !== '' && ($literal[0] === 'b' || $literal[0] === 'B')) {
        $literal = substr($literal, 1);
    }
    $quote = $literal[0] ?? "'";
    $inner = substr($literal, 1, -1);
    if ($quote === "'") {
        return (string) preg_replace('/\\\\([\\\\\'])/', '$1', $inner);
    }

    return (string) preg_replace_callback(
        '/\\\\(?:([nrtvef\\\\$"])|([0-7]{1,3})|x([0-9A-Fa-f]{1,2})|u\{([0-9A-Fa-f]+)\})/',
        static function (array $m): string {
            if (($m[1] ?? '') !== '') {
                return ['n' => "\n", 'r' => "\r", 't' => "\t", 'v' => "\v", 'e' => "\e", 'f' => "\f", '\\' => '\\', '$' => '$', '"' => '"'][$m[1]];
            }
            if (($m[2] ?? '') !== '') {
                return chr(octdec($m[2]) & 255);
            }
            if (($m[3] ?? '') !== '') {
                return chr((int) hexdec($m[3]));
            }

            return mb_chr((int) hexdec($m[4]), 'UTF-8') ?: '';
        },
        $inner
    );
}

/**
 * Reads the text and the domain of a trans() call the way PrestaShop's extractor does: the domain is the
 * third argument (Symfony: trans($id, $params, $domain)) or the second (trans($id, $domain) of
 * TranslatorAwareType and FrameworkBundleAdminController).
 *
 * @param array<int, PhpToken[]> $args
 *
 * @return array{id: ?string, domain: ?string, error: ?string}
 */
function tr_php_trans_call(array $args): array
{
    $positional = [];
    $named = [];
    foreach ($args as $arg) {
        if (count($arg) >= 2 && $arg[0]->id === T_STRING && $arg[1]->text === ':') {
            $named[strtolower($arg[0]->text)] = array_slice($arg, 2);
        } else {
            $positional[] = $arg;
        }
    }
    $idArg = $positional[0] ?? $named['id'] ?? $named['message'] ?? $named['key'] ?? null;
    $id = $idArg !== null ? tr_php_literal($idArg) : null;
    if ($id === null) {
        return ['id' => null, 'domain' => null, 'error' => "Text is not a string literal: PrestaShop's extractor and the Addons validator only see trans('Literal text', ...). Mark a deliberate pass-through with a // " . TR_IGNORE_MARKER . ' comment and the reason.'];
    }

    $domainArg = $named['domain'] ?? null;
    if ($domainArg === null) {
        if (isset($positional[2]) && tr_php_literal($positional[2]) !== null) {
            $domainArg = $positional[2];
        } elseif (isset($positional[1]) && tr_php_literal($positional[1]) !== null) {
            $domainArg = $positional[1];
        } elseif (isset($positional[2])) {
            $domainArg = $positional[2];
        } elseif (isset($positional[1]) && !in_array($positional[1][0]->text, ['['], true) && !$positional[1][0]->is(T_ARRAY)) {
            $domainArg = $positional[1];
        }
    }
    if ($domainArg === null) {
        return ['id' => $id, 'domain' => null, 'error' => "'$id' has no translation domain: add 'Modules.<Module>.Admin' (or .Shop/.Emails) as domain argument."];
    }
    $domain = tr_php_literal($domainArg);
    if ($domain === null) {
        return ['id' => $id, 'domain' => null, 'error' => "The domain of '$id' is not a string literal: PrestaShop's extractor only sees a literal domain."];
    }

    return ['id' => $id, 'domain' => $domain, 'error' => null];
}

/**
 * Splits array items into key and value tokens.
 *
 * @param array<int, PhpToken[]> $parts
 *
 * @return array<int, array{key: ?string, value: PhpToken[], line: int}>
 */
function tr_php_array_items(array $parts): array
{
    $items = [];
    foreach ($parts as $part) {
        if ($part === []) {
            continue;
        }
        $depth = 0;
        $arrow = null;
        foreach ($part as $k => $token) {
            if (in_array($token->text, ['(', '[', '{'], true)) {
                ++$depth;
            } elseif (in_array($token->text, [')', ']', '}'], true)) {
                --$depth;
            } elseif ($depth === 0 && $token->id === T_DOUBLE_ARROW) {
                $arrow = $k;
                break;
            }
        }
        if ($arrow === null) {
            $items[] = ['key' => null, 'value' => $part, 'line' => $part[0]->line];
        } else {
            $items[] = ['key' => tr_php_literal(array_slice($part, 0, $arrow)), 'value' => array_slice($part, $arrow + 1), 'line' => $part[0]->line];
        }
    }

    return $items;
}

/**
 * Texts defined in arrays: ['key' => ..., 'domain' => ..., 'parameters' => ...] (PrestaShop's
 * ArrayTranslationDefinition), tab wordings (ModuleDefinition::TABS), choice labels with a
 * choice_translation_domain, and form labels with a translation_domain. A literal 'label' without a
 * domain is shown untranslated: warning.
 *
 * @param array<int, array{key: ?string, value: PhpToken[], line: int}> $items
 * @param PhpToken[] $tokens
 *
 * @return array{0: array<int, array{0: string, 1: string, 2: int}>, 1: array<int, array{0: string, 1: int, 2: string}>}
 */
function tr_php_array_entries(array $items, array $tokens, string $adminDomain): array
{
    $byKey = [];
    foreach ($items as $item) {
        if ($item['key'] !== null) {
            $byKey[$item['key']] = $item;
        }
    }
    $entries = [];
    $problems = [];
    $literal = static fn (string $key): ?string => isset($byKey[$key]) ? tr_php_literal($byKey[$key]['value']) : null;

    if (isset($byKey['key'], $byKey['domain']) && count($byKey) === count($items)
        && array_diff(array_keys($byKey), ['key', 'domain', 'parameters']) === []
        && $literal('key') !== null && $literal('domain') !== null) {
        $entries[] = [(string) $literal('key'), (string) $literal('domain'), $byKey['key']['line']];
    }
    if (isset($byKey['wording'], $byKey['class_name']) && $literal('wording') !== null) {
        $entries[] = [(string) $literal('wording'), $literal('wording_domain') ?? $adminDomain, $byKey['wording']['line']];
    }
    if (isset($byKey['choices']) && $literal('choice_translation_domain') !== null) {
        $value = $byKey['choices']['value'];
        $first = $value[0] ?? null;
        if ($first !== null && ($first->text === '[' || $first->is(T_ARRAY))) {
            $open = $first->text === '[' ? 0 : 1;
            foreach (tr_php_array_items(tr_php_split($value, $open)) as $choice) {
                if ($choice['key'] !== null && $choice['key'] !== '') {
                    $entries[] = [$choice['key'], (string) $literal('choice_translation_domain'), $choice['line']];
                }
            }
        }
    }
    if (isset($byKey['label']) && ($label = $literal('label')) !== null && trim($label) !== '') {
        if ($literal('translation_domain') !== null) {
            $entries[] = [$label, (string) $literal('translation_domain'), $byKey['label']['line']];
        } elseif (!isset($byKey['translation_domain'])) {
            $problems[] = ['warning', $byKey['label']['line'], "Literal label '$label' is shown untranslated: use \$this->trans('$label', [], '$adminDomain')."];
        }
    }

    return [$entries, $problems];
}

/**
 * Extracts {l s='...' d='...'} tags from a Smarty template.
 *
 * @return array{entries: array<int, array{0: string, 1: string, 2: int}>, problems: array<int, array{0: string, 1: int, 2: string}>}
 */
function tr_extract_smarty(string $code): array
{
    $ignored = [];
    $code = tr_blank_comments($code, '/\{\*.*?\*\}/s', $ignored);
    $code = tr_blank_comments($code, '/\{literal\}.*?\{\/literal\}/s', $ignored, false);
    $entries = [];
    $problems = [];
    $offset = 0;
    while (preg_match('/\{l\s/', $code, $m, PREG_OFFSET_CAPTURE, $offset)) {
        $pos = (int) $m[0][1];
        $line = substr_count($code, "\n", 0, $pos) + 1;
        [$attrs, $end] = tr_smarty_attributes($code, $pos + 2);
        $offset = max($end, $pos + 2);
        if (isset($ignored[$line]) || isset($ignored[$line - 1])) {
            continue;
        }
        $s = $attrs['s'] ?? null;
        if ($s === null) {
            $problems[] = ['error', $line, "{l} without s='…'."];
        } elseif ($s['quote'] !== "'") {
            $problems[] = ['error', $line, $s['quote'] === '"'
                ? "{l} needs s='…' in single quotes (Addons validator, TPL-08)."
                : "Text in {l s=…} is not a string literal: PrestaShop can only extract s='Literal text'."];
        } elseif (isset($attrs['mod'])) {
            $problems[] = ['error', $line, "{l mod=…} is the legacy translation system: use d='Modules.<Module>.Shop' (TR-01)."];
        } elseif (!isset($attrs['d'])) {
            $problems[] = ['error', $line, "{l s='{$s['value']}'} has no domain: add d='Modules.<Module>.Shop' (TPL-08)."];
        } elseif ($attrs['d']['quote'] === null) {
            $problems[] = ['error', $line, "The domain in {l d=…} is not a string literal."];
        } else {
            $entries[] = [$s['value'], $attrs['d']['value'], $line];
        }
    }

    return ['entries' => $entries, 'problems' => $problems];
}

/**
 * Parses the attributes of a Smarty tag from position $i up to the closing "}".
 *
 * @return array{0: array<string, array{quote: ?string, value: string}>, 1: int} attributes and the position after the tag
 */
function tr_smarty_attributes(string $code, int $i): array
{
    $attrs = [];
    $len = strlen($code);
    while ($i < $len) {
        while ($i < $len && ctype_space($code[$i])) {
            ++$i;
        }
        if ($i >= $len) {
            break;
        }
        if ($code[$i] === '}') {
            return [$attrs, $i + 1];
        }
        if (!preg_match('/\G([A-Za-z_][A-Za-z0-9_]*)\s*=\s*/', $code, $m, 0, $i)) {
            $close = strpos($code, '}', $i);

            return [$attrs, $close === false ? $len : $close + 1];
        }
        $name = $m[1];
        $i += strlen($m[0]);
        $char = $code[$i] ?? '';
        if ($char === "'" || $char === '"') {
            [$raw, $i] = tr_read_quoted($code, $i);
            $value = $char === "'" ? (string) preg_replace('/\\\\([\\\\\'])/', '$1', $raw) : $raw;
            $attrs[$name] = ['quote' => $char, 'value' => $value];
        } elseif ($char === '[') {
            $i = tr_skip_balanced($code, $i);
            $attrs[$name] = ['quote' => null, 'value' => ''];
        } else {
            preg_match('/\G[^\s}]*/', $code, $v, 0, $i);
            $i += strlen($v[0]);
            $attrs[$name] = ['quote' => null, 'value' => $v[0]];
        }
    }

    return [$attrs, $len];
}

/**
 * Extracts 'Text'|trans(...) filters, {% trans %} blocks and trans_default_domain from a Twig template.
 *
 * @return array{entries: array<int, array{0: string, 1: string, 2: int}>, problems: array<int, array{0: string, 1: int, 2: string}>}
 */
function tr_extract_twig(string $code): array
{
    $ignored = [];
    $code = tr_blank_comments($code, '/\{#.*?#\}/s', $ignored);
    $entries = [];
    $problems = [];
    $default = null;
    $offset = 0;
    while (preg_match('/\{\{|\{%/', $code, $m, PREG_OFFSET_CAPTURE, $offset)) {
        $start = (int) $m[0][1];
        [$tokens, $end] = tr_twig_tokens($code, $start + 2, $m[0][0] === '{{' ? '}}' : '%}');
        $offset = $end;
        $names = array_values(array_filter($tokens, static fn (array $t): bool => $t['type'] !== 'punct' || $t['value'] !== '-'));
        $tag = $m[0][0] === '{%' && ($names[0]['type'] ?? '') === 'name' ? $names[0]['value'] : null;

        if ($tag === 'trans_default_domain' && ($names[1]['type'] ?? '') === 'string') {
            $default = $names[1]['value'];
            continue;
        }
        if ($tag === 'trans') {
            $line = $names[0]['line'];
            if (!preg_match('/\{%-?\s*endtrans\s*-?%\}/', $code, $close, PREG_OFFSET_CAPTURE, $end)) {
                $problems[] = ['error', $line, '{% trans %} without {% endtrans %}.'];
                continue;
            }
            $body = substr($code, $end, (int) $close[0][1] - $end);
            $offset = (int) $close[0][1] + strlen($close[0][0]);
            $domain = $default;
            foreach ($names as $k => $t) {
                if ($t['type'] === 'name' && $t['value'] === 'from' && ($names[$k + 1]['type'] ?? '') === 'string') {
                    $domain = $names[$k + 1]['value'];
                }
            }
            if (isset($ignored[$line]) || isset($ignored[$line - 1])) {
                continue;
            }
            $source = (string) preg_replace('/\{\{\s*([A-Za-z_][A-Za-z0-9_]*)\s*\}\}/', '%$1%', $body);
            if ($domain === null) {
                $problems[] = ['error', $line, "{% trans %}$source{% endtrans %} has no domain: add from 'Modules.<Module>.Admin'."];
            } else {
                $entries[] = [$source, $domain, $line];
            }
            continue;
        }

        $count = count($tokens);
        for ($k = 1; $k < $count; ++$k) {
            if ($tokens[$k]['type'] !== 'name' || $tokens[$k]['value'] !== 'trans' || ($tokens[$k - 1]['value'] ?? '') !== '|' || $tokens[$k - 1]['type'] !== 'punct') {
                continue;
            }
            $line = $tokens[$k]['line'];
            if (isset($ignored[$line]) || isset($ignored[$line - 1])) {
                continue;
            }
            $subject = $tokens[$k - 2] ?? null;
            if ($subject === null || $subject['type'] !== 'string' || $subject['interp']) {
                $problems[] = ['error', $line, "Text before |trans is not a string literal: PrestaShop's extractor only sees 'Literal text'|trans(…)."];
                continue;
            }
            $domain = $default;
            $domainOk = true;
            if (($tokens[$k + 1]['value'] ?? '') === '(') {
                $positional = [];
                $named = [];
                foreach (tr_twig_args($tokens, $k + 1) as $arg) {
                    if (count($arg) >= 2 && $arg[0]['type'] === 'name' && in_array($arg[1]['value'], ['=', ':'], true) && $arg[1]['type'] === 'punct') {
                        $named[$arg[0]['value']] = array_slice($arg, 2);
                    } else {
                        $positional[] = $arg;
                    }
                }
                $domainArg = $named['domain'] ?? $positional[1] ?? null;
                if ($domainArg !== null) {
                    $domainOk = count($domainArg) === 1 && $domainArg[0]['type'] === 'string' && !$domainArg[0]['interp'];
                    $domain = $domainOk ? $domainArg[0]['value'] : null;
                }
            }
            if (!$domainOk) {
                $problems[] = ['error', $line, "The domain of '{$subject['value']}'|trans is not a string literal."];
            } elseif ($domain === null) {
                $problems[] = ['error', $line, "'{$subject['value']}'|trans has no domain: use |trans({}, 'Modules.<Module>.Admin') or {% trans_default_domain %}."];
            } else {
                $entries[] = [$subject['value'], $domain, $line];
            }
        }
    }

    return ['entries' => $entries, 'problems' => $problems];
}

/**
 * Tokenizes a Twig expression from position $i up to the closer ("}}" or "%}") outside strings.
 *
 * @return array{0: array<int, array{type: string, value: string, interp: bool, line: int}>, 1: int} tokens and the position after the closer
 */
function tr_twig_tokens(string $code, int $i, string $closer): array
{
    $tokens = [];
    $len = strlen($code);
    while ($i < $len) {
        $char = $code[$i];
        if (ctype_space($char)) {
            ++$i;
            continue;
        }
        if (substr($code, $i, 2) === $closer) {
            return [$tokens, $i + 2];
        }
        $line = substr_count($code, "\n", 0, $i) + 1;
        if ($char === "'" || $char === '"') {
            [$raw, $i] = tr_read_quoted($code, $i);
            $tokens[] = ['type' => 'string', 'value' => stripcslashes($raw), 'interp' => $char === '"' && str_contains($raw, '#{'), 'line' => $line];
        } elseif (preg_match('/\G[A-Za-z_][A-Za-z0-9_]*/', $code, $m, 0, $i)) {
            $tokens[] = ['type' => 'name', 'value' => $m[0], 'interp' => false, 'line' => $line];
            $i += strlen($m[0]);
        } elseif (preg_match('/\G\d+(?:\.\d+)?/', $code, $m, 0, $i)) {
            $tokens[] = ['type' => 'number', 'value' => $m[0], 'interp' => false, 'line' => $line];
            $i += strlen($m[0]);
        } else {
            $tokens[] = ['type' => 'punct', 'value' => $char, 'interp' => false, 'line' => $line];
            ++$i;
        }
    }

    return [$tokens, $len];
}

/**
 * Splits the Twig tokens inside the parentheses that open at $open into top-level arguments.
 *
 * @param array<int, array{type: string, value: string, interp: bool, line: int}> $tokens
 *
 * @return array<int, array<int, array{type: string, value: string, interp: bool, line: int}>>
 */
function tr_twig_args(array $tokens, int $open): array
{
    $args = [];
    $current = [];
    $depth = 0;
    $count = count($tokens);
    for ($j = $open; $j < $count; ++$j) {
        $t = $tokens[$j];
        $punct = $t['type'] === 'punct' ? $t['value'] : '';
        if (in_array($punct, ['(', '[', '{'], true)) {
            if ($depth > 0) {
                $current[] = $t;
            }
            ++$depth;
        } elseif (in_array($punct, [')', ']', '}'], true)) {
            --$depth;
            if ($depth === 0) {
                if ($current !== []) {
                    $args[] = $current;
                }

                return $args;
            }
            $current[] = $t;
        } elseif ($punct === ',' && $depth === 1) {
            $args[] = $current;
            $current = [];
        } else {
            $current[] = $t;
        }
    }

    return $args;
}

/**
 * Replaces comments (or other skipped blocks) by spaces, keeping line numbers, and records the lines of
 * comments that contain the ignore marker.
 *
 * @param array<int, bool> $ignored lines with the marker (filled in)
 */
function tr_blank_comments(string $code, string $pattern, array &$ignored, bool $markers = true): string
{
    return (string) preg_replace_callback($pattern, static function (array $m) use ($code, &$ignored, $markers): string {
        if ($markers && str_contains($m[0][0], TR_IGNORE_MARKER)) {
            $first = substr_count($code, "\n", 0, (int) $m[0][1]) + 1;
            for ($l = $first, $last = $first + substr_count($m[0][0], "\n"); $l <= $last; ++$l) {
                $ignored[$l] = true;
            }
        }

        return (string) preg_replace('/[^\n]/', ' ', $m[0][0]);
    }, $code, -1, $count, PREG_OFFSET_CAPTURE);
}

/**
 * Reads a quoted string starting at the quote at position $i (backslash escapes the next character).
 *
 * @return array{0: string, 1: int} the raw content between the quotes and the position after the closing quote
 */
function tr_read_quoted(string $code, int $i): array
{
    $quote = $code[$i];
    $len = strlen($code);
    for ($j = $i + 1; $j < $len; ++$j) {
        if ($code[$j] === '\\') {
            ++$j;
        } elseif ($code[$j] === $quote) {
            return [substr($code, $i + 1, $j - $i - 1), $j + 1];
        }
    }

    return [substr($code, $i + 1), $len];
}

/**
 * Skips a bracketed Smarty array starting at the "[" at position $i, including quoted strings inside.
 */
function tr_skip_balanced(string $code, int $i): int
{
    $depth = 0;
    $len = strlen($code);
    while ($i < $len) {
        $char = $code[$i];
        if ($char === "'" || $char === '"') {
            [, $i] = tr_read_quoted($code, $i);
            continue;
        }
        if ($char === '[') {
            ++$depth;
        } elseif ($char === ']' && --$depth === 0) {
            return $i + 1;
        }
        ++$i;
    }

    return $len;
}

