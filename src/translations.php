/**
 * extract: lists the texts per domain with their references, core-domain texts and problems.
 *
 * @param array<string, mixed> $ctx
 * @param array<string, string|bool> $options
 */
function tr_cmd_extract(array $ctx, array $options): int
{
    $extraction = tr_extract($ctx);
    if (isset($options['json'])) {
        echo json_encode($extraction, JSON_PRETTY_PRINT | JSON_UNESCAPED_SLASHES | JSON_UNESCAPED_UNICODE) . "\n";

        return tr_count_level($extraction['problems'], 'error') > 0 ? 1 : 0;
    }
    $total = 0;
    foreach ($extraction['strings'] as $domain => $sources) {
        echo "$domain (" . count($sources) . ")\n";
        foreach ($sources as $source => $refs) {
            echo '  ' . tr_quote((string) $source) . '  ' . implode(', ', $refs) . "\n";
        }
        $total += count($sources);
    }
    if ($extraction['core'] !== []) {
        echo "Core domains (translated by PrestaShop):\n";
        foreach ($extraction['core'] as $domain => $sources) {
            foreach ($sources as $source => $refs) {
                echo "  $domain " . tr_quote((string) $source) . '  ' . implode(', ', $refs) . "\n";
            }
        }
    }
    if ($extraction['problems'] !== []) {
        echo "Problems:\n";
        tr_print_problems($extraction['problems']);
    }
    echo "$total text(s) in " . count($extraction['strings']) . ' domain(s), ' . tr_count_level($extraction['problems'], 'error') . " error(s).\n";

    return tr_count_level($extraction['problems'], 'error') > 0 ? 1 : 0;
}

/**
 * status: per language what is missing, machine-translated or broken, then the missing texts with the
 * languages that lack them, and the next command to run.
 *
 * @param array<string, mixed> $ctx
 * @param array<string, string|bool> $options
 */
function tr_cmd_status(array $ctx, array $options): int
{
    $extraction = tr_extract($ctx);
    $catalogues = tr_load_all($ctx);
    $analysis = tr_analyse($ctx, $extraction, $catalogues);
    $mails = tr_mails($ctx, $catalogues);
    $pending = tr_build($ctx, $extraction, $catalogues, false);
    if (isset($options['json'])) {
        echo json_encode([
            'module' => $ctx['name'],
            'source' => $ctx['source'],
            'targets' => $ctx['targets'],
            'texts' => array_map('count', $extraction['strings']),
            'languages' => $analysis,
            'mails' => $mails,
            'build' => $pending,
            'problems' => $extraction['problems'],
        ], JSON_PRETTY_PRINT | JSON_UNESCAPED_SLASHES | JSON_UNESCAPED_UNICODE) . "\n";

        return 0;
    }

    $domains = [];
    foreach ($extraction['strings'] as $domain => $sources) {
        $domains[] = tr_short($ctx, $domain) . ' ' . count($sources);
    }
    echo "{$ctx['name']}: " . array_sum(array_map('count', $extraction['strings'])) . ' text(s) (' . (implode(', ', $domains) ?: 'none')
        . "), source {$ctx['source']}, targets: " . (implode(' ', $ctx['targets']) ?: 'none') . "\n";
    if (!$ctx['hasI18n']) {
        echo "  No i18n.json in the repository: only the source language. Add {\"source\": \"en\", \"languages\": [\"en\", \"fr\", ...]}.\n";
    }
    $missingByText = [];
    foreach ($analysis as $iso => $state) {
        $parts = [];
        foreach (['missing' => 'missing', 'broken' => 'broken placeholders', 'machine' => 'machine (review)', 'obsolete' => 'obsolete'] as $key => $label) {
            if ($state[$key] !== []) {
                $parts[] = count($state[$key]) . " $label";
            }
        }
        if (isset($mails['problems'][$iso])) {
            $parts[] = count($mails['problems'][$iso]) . ' mail problem(s)';
        }
        printf("  %-3s %s\n", $iso, $parts === [] ? 'ok' : implode(', ', $parts));
        foreach ($state['missing'] as [$domain, $source]) {
            $missingByText[$domain . "\0" . $source][] = $iso;
        }
    }
    if ($missingByText !== []) {
        echo "Missing (text -> languages):\n";
        foreach ($missingByText as $key => $isos) {
            [$domain, $source] = explode("\0", $key, 2);
            echo '  ' . tr_short($ctx, $domain) . ' ' . tr_quote($source) . ' -> ' . (count($isos) === count($ctx['targets']) ? 'all' : implode(' ', $isos)) . "\n";
        }
    }
    foreach ($analysis as $iso => $state) {
        foreach ($state['broken'] as [$domain, $source, $problem]) {
            echo "  BROKEN $iso " . tr_short($ctx, $domain) . ' ' . tr_quote($source) . ": $problem\n";
        }
    }
    foreach ($mails['problems'] as $iso => $problems) {
        foreach ($problems as [$level, $message]) {
            echo '  ' . ($level === 'error' ? 'MAIL ' : 'mail warning ') . "$iso: $message\n";
        }
    }
    if ($extraction['problems'] !== []) {
        echo "Source problems:\n";
        tr_print_problems($extraction['problems']);
    }
    if ($pending !== []) {
        echo '  XLF/mail records not up to date (' . count($pending) . " change(s)): vendor/bin/ps-module translations build\n";
    }
    if ($missingByText !== []) {
        $hits = tr_glossary_hits($analysis);
        echo "Next:\n";
        if ($hits > 0) {
            echo "  vendor/bin/ps-module translations fill            ($hits from the shared glossary)\n";
        }
        echo "  vendor/bin/ps-module translations todo --out=../.cache/i18n-todo.json\n"
            . "  translate the empty values in that file, then: vendor/bin/ps-module translations apply ../.cache/i18n-todo.json\n";
    }

    return 0;
}

/**
 * todo: writes a JSON skeleton of the missing texts (domain -> text -> ISO -> ""), with the reference of
 * each text and the language names, for a translator (Claude or a person) to fill in.
 *
 * @param array<string, mixed> $ctx
 * @param string[] $args
 * @param array<string, string|bool> $options
 */
function tr_cmd_todo(array $ctx, array $args, array $options): int
{
    $isos = tr_isos($ctx, $args);
    $extraction = tr_extract($ctx);
    $catalogues = tr_load_all($ctx);
    $withMachine = isset($options['with-machine']);
    $languages = [];
    foreach ($isos as $iso) {
        $languages[$iso] = $ctx['languages'][$iso]['name'] . (!empty($ctx['languages'][$iso]['rtl']) ? ' (right-to-left)' : '');
    }
    $todo = [
        '_instructions' => 'Translate each empty value from English into the language of its key (see _languages). Keep placeholders (%name%, %s, %1$s), tag markers ([1]...[/1]) and HTML tags exactly. Admin = back office for the merchant, Shop = the customer-facing shop, Emails = e-mails. Pre-filled values are machine translations to review or translations with broken placeholders to fix. Then run: vendor/bin/ps-module translations apply <this file>',
        '_languages' => $languages,
    ];
    $count = 0;
    foreach ($extraction['strings'] as $domain => $sources) {
        foreach ($sources as $source => $refs) {
            $values = [];
            foreach ($isos as $iso) {
                $entry = $catalogues[$iso]['strings'][$domain][$source] ?? null;
                if ($entry === null || trim($entry['text']) === '') {
                    $values[$iso] = '';
                } elseif ($withMachine && $entry['machine'] !== null) {
                    $values[$iso] = $entry['text'];
                } elseif (tr_placeholder_problem((string) $source, $entry['text']) !== null) {
                    $values[$iso] = $entry['text'];
                }
            }
            if ($values !== []) {
                $todo[$domain][(string) $source] = ['_ref' => $refs[0] . (count($refs) > 1 ? ' (+' . (count($refs) - 1) . ')' : '')] + $values;
                $count += count($values);
            }
        }
    }
    $json = json_encode($todo, JSON_PRETTY_PRINT | JSON_UNESCAPED_SLASHES | JSON_UNESCAPED_UNICODE) . "\n";
    if (isset($options['out']) && is_string($options['out'])) {
        $out = tr_user_path($ctx, $options['out']);
        if (!is_dir(dirname($out))) {
            mkdir(dirname($out), 0775, true);
        }
        file_put_contents($out, $json);
        fwrite(STDERR, "$count translation(s) to do, written to $out\n");
    } else {
        echo $json;
        fwrite(STDERR, "$count translation(s) to do.\n");
    }

    return 0;
}

/**
 * apply: merges a filled-in todo file into the catalogues (checking placeholders), then builds.
 *
 * @param array<string, mixed> $ctx
 * @param string[] $args
 * @param array<string, string|bool> $options
 */
function tr_cmd_apply(array $ctx, array $args, array $options): int
{
    $file = isset($args[0]) && $args[0] !== '-' ? tr_user_path($ctx, $args[0]) : ($args[0] ?? '');
    $raw = $file === '-' ? (string) stream_get_contents(STDIN) : (is_file($file) ? (string) file_get_contents($file) : '');
    $data = json_decode($raw, true);
    if (!is_array($data)) {
        fwrite(STDERR, "Usage: ps-module translations apply <todo.json|-> [--machine=<engine>] (file missing or not valid JSON)\n");

        return 2;
    }
    $machine = isset($options['machine']) ? (is_string($options['machine']) ? $options['machine'] : 'machine') : null;
    $extraction = tr_extract($ctx);
    $catalogues = tr_load_all($ctx);
    $applied = 0;
    $errors = 0;
    $changed = [];
    foreach ($data as $domain => $sources) {
        if (str_starts_with((string) $domain, '_') || !is_array($sources)) {
            continue;
        }
        if (!str_starts_with((string) $domain, $ctx['prefix'])) {
            echo "skipped: '$domain' is not a domain of this module.\n";
            continue;
        }
        foreach ($sources as $source => $values) {
            if (str_starts_with((string) $source, '_') || !is_array($values)) {
                continue;
            }
            if (!isset($extraction['strings'][$domain][$source])) {
                echo 'note: ' . tr_quote((string) $source) . " is not in the code (stored, but obsolete).\n";
            }
            foreach ($values as $iso => $text) {
                if (str_starts_with((string) $iso, '_') || !is_string($text) || trim($text) === '') {
                    continue;
                }
                if (!isset($catalogues[$iso])) {
                    echo "skipped: '$iso' is not a target language in i18n.json.\n";
                    continue;
                }
                $problem = tr_placeholder_problem((string) $source, $text);
                if ($problem !== null) {
                    echo "ERROR $iso " . tr_quote((string) $source) . ": $problem\n";
                    ++$errors;
                    continue;
                }
                $current = $catalogues[$iso]['strings'][$domain][$source] ?? null;
                if ($current !== null && $current['text'] === $text && $current['machine'] === $machine) {
                    continue;
                }
                $catalogues[$iso]['strings'][$domain][(string) $source] = ['text' => $text, 'machine' => $machine];
                $changed[$iso] = true;
                ++$applied;
            }
        }
    }
    foreach (array_keys($changed) as $iso) {
        tr_save_catalogue($ctx, $iso, $catalogues[$iso]);
    }
    ps_vlog('translations: apply ' . ($file === '-' ? 'from stdin' : $file) . ($machine !== null ? ", marked machine ($machine)" : ', marked reviewed'));
    echo "Applied $applied translation(s) to " . count($changed) . " catalogue(s)" . ($errors > 0 ? ", $errors rejected" : '') . ".\n";
    tr_rebuild($ctx);

    return $errors > 0 ? 1 : 0;
}

/**
 * fill: fills missing texts from the shared glossary (texts of the template and the feature recipes,
 * translated and reviewed once for all modules), then builds.
 *
 * @param array<string, mixed> $ctx
 */
function tr_cmd_fill(array $ctx): int
{
    $glossary = tr_glossary();
    ps_vlog('translations: glossary ' . dirname(__DIR__) . '/resources/translations/glossary.json, ' . count($glossary) . ' text(s)');
    $extraction = tr_extract($ctx);
    $catalogues = tr_load_all($ctx);
    $filled = 0;
    foreach (tr_analyse($ctx, $extraction, $catalogues) as $iso => $state) {
        $changed = false;
        $before = $filled;
        foreach ($state['missing'] as [$domain, $source]) {
            if (isset($glossary[$source][$iso])) {
                $catalogues[$iso]['strings'][$domain][$source] = ['text' => (string) $glossary[$source][$iso], 'machine' => null];
                $changed = true;
                ++$filled;
            }
        }
        if ($state['missing'] !== []) {
            ps_vlog("translations: $iso: " . ($filled - $before) . ' of ' . count($state['missing']) . ' missing text(s) found in the glossary');
        }
        if ($changed || !is_file($ctx['catalogueDir'] . "/$iso.json")) {
            tr_save_catalogue($ctx, $iso, $catalogues[$iso]);
        }
    }
    echo "Filled $filled translation(s) from the glossary.\n";
    tr_rebuild($ctx);

    return 0;
}

/**
 * auto: fills missing texts with DeepL when DEEPL_API_KEY is set (environment or the nearest .env upwards).
 * The results are marked "machine" until someone reviews them (accept, or apply a reviewed todo file).
 *
 * @param array<string, mixed> $ctx
 * @param string[] $args
 */
function tr_cmd_auto(array $ctx, array $args): int
{
    $key = tr_env('DEEPL_API_KEY', $ctx['repoDir']);
    if ($key === '') {
        echo "No DEEPL_API_KEY (environment or .env). Translate the texts yourself instead:\n"
            . "  vendor/bin/ps-module translations todo --out=../.cache/i18n-todo.json\n"
            . "  (Claude: fill in every empty value, keeping placeholders), then\n"
            . "  vendor/bin/ps-module translations apply ../.cache/i18n-todo.json\n";

        return 1;
    }
    // Never shown in verbose output.
    ps_vsecret($key);
    $isos = tr_isos($ctx, $args);
    ps_vlog('translations: DeepL for ' . implode(' ', $isos) . ' (key from ' . (getenv('DEEPL_API_KEY') ? 'the environment' : 'a .env file') . ', ' . (str_ends_with($key, ':fx') ? 'free' : 'pro') . ' API)');
    $extraction = tr_extract($ctx);
    $catalogues = tr_load_all($ctx);
    $analysis = tr_analyse($ctx, $extraction, $catalogues);
    $total = 0;
    $failed = 0;
    foreach ($isos as $iso) {
        $missing = $analysis[$iso]['missing'];
        if ($missing === []) {
            continue;
        }
        foreach (array_chunk($missing, 50) as $chunk) {
            $protected = array_map(static fn (array $m): array => tr_protect($m[1]), $chunk);
            try {
                $results = tr_deepl($key, array_column($protected, 0), strtoupper($ctx['source']), tr_deepl_language($iso));
            } catch (RuntimeException $e) {
                echo "DeepL $iso: " . $e->getMessage() . "\n";
                $failed += count($chunk);
                continue 2;
            }
            foreach ($chunk as $n => [$domain, $source]) {
                $text = tr_unprotect($results[$n] ?? '', $protected[$n][1]);
                $problem = $text === null ? 'placeholders lost or invented' : tr_placeholder_problem($source, $text);
                if ($text === null || $problem !== null) {
                    echo "skipped $iso " . tr_quote($source) . ": $problem\n";
                    ++$failed;
                    continue;
                }
                $catalogues[$iso]['strings'][$domain][$source] = ['text' => $text, 'machine' => 'deepl'];
                ++$total;
            }
        }
        tr_save_catalogue($ctx, $iso, $catalogues[$iso]);
        ps_vlog("translations: $iso: DeepL done, " . count($missing) . ' text(s) sent');
    }
    echo "DeepL: $total translation(s) added (marked machine, review them: translations todo --with-machine)" . ($failed > 0 ? ", $failed failed" : '') . ".\n";
    tr_rebuild($ctx);

    return $failed > 0 ? 1 : 0;
}

/**
 * accept: marks the machine translations of the given languages as reviewed.
 *
 * @param array<string, mixed> $ctx
 * @param string[] $args
 */
function tr_cmd_accept(array $ctx, array $args): int
{
    if ($args === []) {
        fwrite(STDERR, "Usage: ps-module translations accept <iso>...|all\n");

        return 2;
    }
    $accepted = 0;
    foreach (tr_isos($ctx, $args) as $iso) {
        $catalogue = tr_load_catalogue($ctx, $iso);
        $changed = false;
        foreach ($catalogue['strings'] as $domain => $entries) {
            foreach ($entries as $source => $entry) {
                if ($entry['machine'] !== null) {
                    $catalogue['strings'][$domain][$source]['machine'] = null;
                    $changed = true;
                    ++$accepted;
                }
            }
        }
        if ($changed) {
            tr_save_catalogue($ctx, $iso, $catalogue);
        }
    }
    echo "Accepted $accepted machine translation(s).\n";
    tr_rebuild($ctx);

    return 0;
}

/**
 * prune: removes catalogue texts that are no longer in the code.
 *
 * @param array<string, mixed> $ctx
 */
function tr_cmd_prune(array $ctx): int
{
    $extraction = tr_extract($ctx);
    $removed = 0;
    foreach ($ctx['targets'] as $iso) {
        $catalogue = tr_load_catalogue($ctx, $iso);
        $before = $catalogue;
        foreach ($catalogue['strings'] as $domain => $entries) {
            foreach (array_keys($entries) as $source) {
                if (!isset($extraction['strings'][$domain][$source])) {
                    unset($catalogue['strings'][$domain][$source]);
                    ++$removed;
                }
            }
            if ($catalogue['strings'][$domain] === []) {
                unset($catalogue['strings'][$domain]);
            }
        }
        if ($catalogue !== $before) {
            tr_save_catalogue($ctx, $iso, $catalogue);
        }
    }
    echo "Removed $removed obsolete text(s).\n";
    tr_rebuild($ctx);

    return 0;
}

/**
 * mails-ok: records that the mail templates of these languages are translated from the current source
 * version (after updating them for a changed mails/en/ file).
 *
 * @param array<string, mixed> $ctx
 * @param string[] $args
 */
function tr_cmd_mails_ok(array $ctx, array $args): int
{
    if ($args === []) {
        fwrite(STDERR, "Usage: ps-module translations mails-ok <iso>...|all\n");

        return 2;
    }
    $sourceDir = $ctx['moduleDir'] . '/mails/' . tr_ps_iso($ctx, $ctx['source']);
    $files = tr_mails($ctx, tr_load_all($ctx))['files'];
    foreach (tr_isos($ctx, $args) as $iso) {
        $catalogue = tr_load_catalogue($ctx, $iso);
        foreach ($files as $file) {
            if (is_file($ctx['moduleDir'] . '/mails/' . tr_ps_iso($ctx, $iso) . "/$file")) {
                $catalogue['mails'][$file] = sha1(str_replace("\r\n", "\n", (string) file_get_contents("$sourceDir/$file")));
            }
        }
        $catalogue['mails'] = array_intersect_key($catalogue['mails'], array_flip($files));
        tr_save_catalogue($ctx, $iso, $catalogue);
        echo "$iso: mail templates confirmed against the current mails/{$ctx['source']}/.\n";
    }

    return 0;
}

/**
 * build: generates the XLF files and index.php files, and records the source version of new mail translations.
 *
 * @param array<string, mixed> $ctx
 */
function tr_cmd_build(array $ctx): int
{
    $extraction = tr_extract($ctx);
    $changes = tr_build($ctx, $extraction, tr_load_all($ctx), true);
    foreach ($changes as $change) {
        echo "  $change\n";
    }
    echo $changes === [] ? "Translations are up to date.\n" : count($changes) . " change(s).\n";
    $errors = tr_count_level($extraction['problems'], 'error');
    if ($errors > 0) {
        echo "$errors source problem(s): vendor/bin/ps-module translations extract\n";
    }

    return 0;
}

/**
 * check: fails when a text cannot be extracted, a language misses texts or mails, placeholders differ,
 * or the XLF files are not built from the current catalogues. Obsolete and machine texts are warnings.
 *
 * @param array<string, mixed> $ctx
 */
function tr_cmd_check(array $ctx): int
{
    $extraction = tr_extract($ctx);
    $catalogues = tr_load_all($ctx);
    $analysis = tr_analyse($ctx, $extraction, $catalogues);
    $mails = tr_mails($ctx, $catalogues);
    $pending = tr_build($ctx, $extraction, $catalogues, false);
    $errors = [];
    $warnings = [];

    foreach ($extraction['problems'] as $p) {
        if ($p['level'] === 'error') {
            $errors[] = $p['ref'] . ' ' . $p['message'];
        } else {
            $warnings[] = $p['ref'] . ' ' . $p['message'];
        }
    }
    $missing = [];
    $machine = [];
    $obsolete = 0;
    foreach ($analysis as $iso => $state) {
        if ($state['missing'] !== []) {
            $missing[] = "$iso " . count($state['missing']);
        }
        foreach ($state['broken'] as [$domain, $source, $problem]) {
            $errors[] = "$iso " . tr_short($ctx, $domain) . ' ' . tr_quote($source) . ": $problem (fix it in i18n/$iso.json)";
        }
        if ($state['machine'] !== []) {
            $machine[] = "$iso " . count($state['machine']);
        }
        $obsolete += count($state['obsolete']);
    }
    if ($missing !== []) {
        $errors[] = 'Missing translations (' . implode(', ', $missing) . '): vendor/bin/ps-module translations status';
    }
    foreach ($mails['problems'] as $iso => $problems) {
        foreach ($problems as [$level, $message]) {
            if ($level === 'error') {
                $errors[] = "$iso: $message";
            } else {
                $warnings[] = "$iso: $message";
            }
        }
    }
    if ($pending !== []) {
        $errors[] = 'Translation files are not built from the current catalogues (' . count($pending) . ' change(s), e.g. ' . $pending[0] . '): vendor/bin/ps-module translations build';
    }
    if ($machine !== []) {
        $warnings[] = 'Machine translations not reviewed (' . implode(', ', $machine) . '): vendor/bin/ps-module translations todo --with-machine, or translations accept <iso>';
    }
    if ($obsolete > 0) {
        $warnings[] = "$obsolete obsolete catalogue text(s) (no longer in the code): vendor/bin/ps-module translations prune";
    }

    $texts = array_sum(array_map('count', $extraction['strings']));
    foreach ($warnings as $warning) {
        echo "  warning: $warning\n";
    }
    if ($errors === []) {
        echo "Translations OK: $texts text(s) in " . (count($ctx['targets']) + 1) . ' language(s) (' . implode(' ', array_merge([$ctx['source']], $ctx['targets'])) . ")"
            . ($mails['files'] !== [] ? ', ' . count($mails['files']) . ' mail file(s)' : '') . ".\n";

        return 0;
    }
    foreach ($errors as $error) {
        echo "  ERROR $error\n";
    }
    echo 'Translations check failed: ' . count($errors) . " error(s).\n";

    return 1;
}

/**
 * Prints the usage (the comment block at the top of this file).
 */
function tr_help(string $command): int
{
    $source = (string) file_get_contents(__FILE__);
    preg_match('#/\*\n(.*?)\*/#s', substr($source, (int) strpos($source, '/*', 10)), $m);
    echo trim((string) preg_replace('/^ \* ?/m', '', $m[1] ?? '')) . "\n";

    return $command === 'help' ? 0 : 2;
}

