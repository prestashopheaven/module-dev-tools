/**
 * The placeholders of a text: Symfony-style (%name%), sprintf (%s, %1$d), PrestaShop tag markers ([1]..[/1])
 * and HTML tags.
 *
 * @return array{classic: string[], sprintf: string[], positional: bool, markers: string[], html: string[]}
 */
function tr_placeholders(string $text): array
{
    preg_match_all(TR_CLASSIC, $text, $classic);
    $rest = str_replace('%%', '', (string) preg_replace(TR_CLASSIC, '', $text));
    preg_match_all(TR_SPRINTF, $rest, $sprintf);
    preg_match_all('/\[\/?\d+\]/', $text, $markers);
    preg_match_all('/<(\/?)([a-zA-Z][a-zA-Z0-9]*)\b[^>]*>/', $text, $html, PREG_SET_ORDER);

    return [
        'classic' => $classic[0],
        'sprintf' => $sprintf[0],
        'positional' => (bool) preg_grep('/^%\d+\$/', $sprintf[0]),
        'markers' => $markers[0],
        'html' => array_map(static fn (array $m): string => '<' . $m[1] . strtolower($m[2]) . '>', $html),
    ];
}

/**
 * Describes how the placeholders of a translation differ from the source, or null when they match.
 * sprintf placeholders without position must keep their order; everything else only its count.
 */
function tr_placeholder_problem(string $source, string $translation): ?string
{
    $a = tr_placeholders($source);
    $b = tr_placeholders($translation);
    $problems = [];
    foreach (['classic' => 'placeholders', 'markers' => 'tag markers', 'html' => 'HTML tags'] as $key => $label) {
        $x = $a[$key];
        $y = $b[$key];
        sort($x);
        sort($y);
        if ($x !== $y) {
            $problems[] = "$label " . tr_list($a[$key]) . ' in the source, ' . tr_list($b[$key]) . ' in the translation';
        }
    }
    $x = $a['sprintf'];
    $y = $b['sprintf'];
    if ($a['positional'] || $b['positional']) {
        sort($x);
        sort($y);
    }
    if ($x !== $y) {
        $problems[] = 'sprintf placeholders ' . tr_list($a['sprintf']) . ' in the source, ' . tr_list($b['sprintf']) . ' in the translation' . ($a['positional'] ? '' : ' (same order needed, or use %1$s)');
    }

    return $problems === [] ? null : implode('; ', $problems);
}

/**
 * Formats a list of placeholders for a message ("none" when empty).
 *
 * @param string[] $items
 */
function tr_list(array $items): string
{
    return $items === [] ? 'none' : implode(' ', $items);
}

