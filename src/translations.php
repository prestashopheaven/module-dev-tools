/**
 * Collects everything the commands need: module name and domain prefix, repository, languages.
 *
 * @return array<string, mixed>
 */
function tr_context(string $moduleDir): array
{
    $name = basename($moduleDir);
    $repoDir = dod_repo_dir($moduleDir) ?? dirname($moduleDir);
    $languages = tr_read_json(dirname(__DIR__) . '/resources/languages.json')['languages'] ?? [];
    $i18nFile = $repoDir . '/i18n.json';
    $i18n = is_file($i18nFile) ? tr_read_json($i18nFile) : [];
    $source = (string) ($i18n['source'] ?? 'en');
    $enabled = array_values(array_unique(array_map('strval', (array) ($i18n['languages'] ?? [$source]))));
    foreach (array_merge([$source], $enabled) as $iso) {
        if (!isset($languages[$iso])) {
            fwrite(STDERR, "i18n.json: unknown language '$iso'. Available: " . implode(', ', array_keys($languages)) . "\n");
            exit(2);
        }
    }
    // Same as DomainHelper::buildModuleBaseDomain() of PrestaShop's translation tools.
    $component = ucfirst(str_replace('_', '', strtolower(str_starts_with($name, 'ps_') ? substr($name, 3) : $name)));

    return [
        'name' => $name,
        'class' => $component,
        'prefix' => 'Modules.' . $component . '.',
        'adminDomain' => 'Modules.' . $component . '.Admin',
        'moduleDir' => $moduleDir,
        'repoDir' => dod_norm($repoDir),
        'catalogueDir' => dod_norm($repoDir) . '/i18n',
        'hasI18n' => is_file($i18nFile),
        'languages' => $languages,
        'source' => $source,
        'targets' => array_values(array_diff($enabled, [$source])),
    ];
}

/**
 * Reads a JSON file into an array; stops with a clear message when the file is invalid.
 *
 * @return array<string, mixed>
 */
function tr_read_json(string $file): array
{
    if (!is_file($file)) {
        return [];
    }
    $data = json_decode((string) file_get_contents($file), true);
    if (!is_array($data)) {
        fwrite(STDERR, "Invalid JSON in $file: " . json_last_error_msg() . "\n");
        exit(2);
    }

    return $data;
}

/**
 * Writes pretty, diff-friendly JSON (unescaped UTF-8 and slashes, newline at the end).
 *
 * @param array<string, mixed> $data
 */
function tr_write_json(string $file, array $data): void
{
    if (!is_dir(dirname($file))) {
        mkdir(dirname($file), 0775, true);
    }
    file_put_contents($file, json_encode($data, JSON_PRETTY_PRINT | JSON_UNESCAPED_SLASHES | JSON_UNESCAPED_UNICODE) . "\n");
}

/**
 * The PrestaShop locale of an ISO code (fr -> fr-FR), used for the XLF directories.
 *
 * @param array<string, mixed> $ctx
 */
function tr_locale(array $ctx, string $iso): string
{
    return (string) $ctx['languages'][$iso]['locale'];
}

/**
 * The ISO code PrestaShop uses for a language (ps_language.iso_code, also the mails/ directory).
 * Differs from the ISO 639-1 code for Slovenian (si) and Vietnamese (vn).
 *
 * @param array<string, mixed> $ctx
 */
function tr_ps_iso(array $ctx, string $iso): string
{
    return (string) ($ctx['languages'][$iso]['ps_iso'] ?? $iso);
}

/**
 * Module files that can contain translatable texts (PHP, Smarty, Twig), relative to the module directory.
 *
 * @return string[]
 */
function tr_source_files(string $moduleDir): array
{
    $files = [];
    $iterator = new RecursiveIteratorIterator(
        new RecursiveCallbackFilterIterator(
            new RecursiveDirectoryIterator($moduleDir, FilesystemIterator::SKIP_DOTS),
            static fn (SplFileInfo $f): bool => !($f->isDir() && in_array($f->getFilename(), TR_SKIP_DIRS, true))
        )
    );
    foreach ($iterator as $file) {
        $relative = substr(str_replace('\\', '/', $file->getPathname()), strlen($moduleDir) + 1);
        if (preg_match('/\.(php|tpl|twig)$/', $relative) && basename($relative) !== 'index.php'
            && !str_starts_with(basename($relative), '.php-cs-fixer')) {
            $files[] = $relative;
        }
    }
    sort($files);

    return $files;
}

