/**
 * Loads the catalogue of a language; a missing file is an empty catalogue.
 *
 * @param array<string, mixed> $ctx
 *
 * @return array{strings: array<string, array<string, array{text: string, machine: ?string}>>, mails: array<string, string>}
 */
function tr_load_catalogue(array $ctx, string $iso): array
{
    $data = tr_read_json($ctx['catalogueDir'] . '/' . $iso . '.json');
    $strings = [];
    foreach ((array) ($data['strings'] ?? []) as $domain => $entries) {
        foreach ((array) $entries as $source => $value) {
            if (is_array($value)) {
                $strings[(string) $domain][(string) $source] = ['text' => (string) ($value['text'] ?? ''), 'machine' => isset($value['machine']) ? (string) $value['machine'] : null];
            } else {
                $strings[(string) $domain][(string) $source] = ['text' => (string) $value, 'machine' => null];
            }
        }
    }

    return ['strings' => $strings, 'mails' => array_map('strval', (array) ($data['mails'] ?? []))];
}

/**
 * Saves a catalogue sorted by domain and text, so that diffs stay small and reviewable.
 *
 * @param array<string, mixed> $ctx
 * @param array{strings: array<string, array<string, array{text: string, machine: ?string}>>, mails: array<string, string>} $catalogue
 */
function tr_save_catalogue(array $ctx, string $iso, array $catalogue): void
{
    $strings = [];
    ksort($catalogue['strings'], SORT_STRING);
    foreach ($catalogue['strings'] as $domain => $entries) {
        ksort($entries, SORT_STRING);
        foreach ($entries as $source => $entry) {
            $strings[$domain][$source] = $entry['machine'] === null ? $entry['text'] : ['text' => $entry['text'], 'machine' => $entry['machine']];
        }
    }
    $mails = $catalogue['mails'];
    ksort($mails, SORT_STRING);
    $name = $ctx['languages'][$iso]['name'];
    tr_write_json($ctx['catalogueDir'] . '/' . $iso . '.json', [
        '_comment' => "$name translations of {$ctx['name']}: domain -> English text -> translation. {\"text\": …, \"machine\": …} = machine translation, not reviewed yet. After editing: vendor/bin/ps-module translations build",
        'language' => $iso,
        'locale' => tr_locale($ctx, $iso),
        'strings' => $strings === [] ? new stdClass() : $strings,
        'mails' => $mails === [] ? new stdClass() : $mails,
    ]);
    ps_vlog("translations: saved {$ctx['catalogueDir']}/$iso.json (" . array_sum(array_map('count', $strings)) . ' text(s), ' . count($mails) . ' mail version(s))');
}

/**
 * Loads the catalogues of all target languages.
 *
 * @param array<string, mixed> $ctx
 *
 * @return array<string, array{strings: array<string, array<string, array{text: string, machine: ?string}>>, mails: array<string, string>}>
 */
function tr_load_all(array $ctx): array
{
    $catalogues = [];
    foreach ($ctx['targets'] as $iso) {
        $catalogues[$iso] = tr_load_catalogue($ctx, $iso);
    }

    return $catalogues;
}

