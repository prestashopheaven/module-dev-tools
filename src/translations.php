/**
 * Short domain name for compact output: "Admin" for "Modules.<Module>.Admin".
 *
 * @param array<string, mixed> $ctx
 */
function tr_short(array $ctx, string $domain): string
{
    return str_starts_with($domain, $ctx['prefix']) ? substr($domain, strlen($ctx['prefix'])) : $domain;
}

/**
 * Quotes a text for one-line output (newlines visible as \n).
 */
function tr_quote(string $text): string
{
    return '"' . str_replace(["\n", '"'], ['\n', '\"'], $text) . '"';
}

/**
 * Prints extraction problems, errors first.
 *
 * @param array<int, array{level: string, ref: string, message: string}> $problems
 */
function tr_print_problems(array $problems, string $indent = '  '): void
{
    usort($problems, static fn (array $a, array $b): int => [$a['level'] === 'error' ? 0 : 1, strnatcmp($a['ref'], $b['ref'])] <=> [$b['level'] === 'error' ? 0 : 1, 0]);
    foreach ($problems as $p) {
        echo $indent . ($p['level'] === 'error' ? 'ERROR ' : 'warning ') . $p['ref'] . ' ' . $p['message'] . "\n";
    }
}

/**
 * Counts the problems of one level.
 *
 * @param array<int, array{level: string, ref: string, message: string}> $problems
 */
function tr_count_level(array $problems, string $level): int
{
    return count(array_filter($problems, static fn (array $p): bool => $p['level'] === $level));
}

/**
 * Number of entries in the glossary that can fill a missing text, per language.
 *
 * @param array<string, array{missing: array<int, array{0: string, 1: string}>}> $analysis
 */
function tr_glossary_hits(array $analysis): int
{
    $glossary = tr_glossary();
    $hits = 0;
    foreach ($analysis as $iso => $state) {
        foreach ($state['missing'] as [, $source]) {
            if (isset($glossary[$source][$iso])) {
                ++$hits;
            }
        }
    }

    return $hits;
}

/**
 * The shared glossary: translations of texts that many modules use (the template and the feature recipes).
 *
 * @return array<string, array<string, string>> English text => ISO code => translation
 */
function tr_glossary(): array
{
    return (array) (tr_read_json(dirname(__DIR__) . '/resources/translations/glossary.json')['strings'] ?? []);
}

/**
 * Resolves a file path from the command line: relative paths are relative to the module directory,
 * where vendor/bin/ps-module is run (the script itself runs in the repository root).
 *
 * @param array<string, mixed> $ctx
 */
function tr_user_path(array $ctx, string $path): string
{
    $path = str_replace('\\', '/', $path);
    $absolute = str_starts_with($path, '/') || preg_match('#^[A-Za-z]:/#', $path) === 1;

    return $absolute ? $path : $ctx['moduleDir'] . '/' . $path;
}

/**
 * Validates ISO codes given on the command line ("all" = every target language).
 *
 * @param array<string, mixed> $ctx
 * @param string[] $args
 *
 * @return string[]
 */
function tr_isos(array $ctx, array $args): array
{
    if ($args === [] || $args === ['all']) {
        return $ctx['targets'];
    }
    foreach ($args as $iso) {
        if (!in_array($iso, $ctx['targets'], true)) {
            fwrite(STDERR, "'$iso' is not a target language in i18n.json (" . implode(', ', $ctx['targets']) . ").\n");
            exit(2);
        }
    }

    return $args;
}

