/**
 * Reads a setting from the environment or the nearest .env file upwards from $dir (the value is never printed).
 */
function tr_env(string $name, string $dir): string
{
    $value = getenv($name);
    if (is_string($value) && $value !== '') {
        return $value;
    }
    for ($d = $dir; $d !== '' && $d !== dirname($d); $d = dirname($d)) {
        if (is_file("$d/.env") && preg_match('/^\s*' . preg_quote($name, '/') . '\s*=\s*["\']?([^"\'\r\n]*)/m', (string) file_get_contents("$d/.env"), $m) && trim($m[1]) !== '') {
            return trim($m[1]);
        }
    }

    return '';
}

/**
 * The DeepL target language code of an ISO code (pt -> PT-PT, zh -> ZH-HANS, no -> NB).
 */
function tr_deepl_language(string $iso): string
{
    return ['pt' => 'PT-PT', 'zh' => 'ZH-HANS', 'no' => 'NB', 'en' => 'EN-US'][$iso] ?? strtoupper($iso);
}

/**
 * Turns a text into DeepL XML: placeholders, tag markers and HTML tags become <x i="N"/> tags that DeepL keeps.
 *
 * @return array{0: string, 1: string[]} the XML text and the replaced parts
 */
function tr_protect(string $text): array
{
    $pattern = '/(%\w+%|%(?:\d+\$)?[+-]?(?:0|\'.)?-?\d*(?:\.\d+)?[bcdeufFosxX]|\[\/?\d+\]|<[^>]+>)/';
    $parts = preg_split($pattern, $text, -1, PREG_SPLIT_DELIM_CAPTURE) ?: [$text];
    $xml = '';
    $kept = [];
    foreach ($parts as $n => $part) {
        if ($n % 2 === 0) {
            $xml .= htmlspecialchars($part, ENT_XML1 | ENT_NOQUOTES, 'UTF-8');
        } else {
            $xml .= '<x i="' . count($kept) . '"/>';
            $kept[] = $part;
        }
    }

    return [$xml, $kept];
}

/**
 * Restores the parts that tr_protect() replaced; null when DeepL dropped or invented one.
 *
 * @param string[] $kept
 */
function tr_unprotect(string $xml, array $kept): ?string
{
    $used = 0;
    $text = preg_replace_callback('/<x\s+i="(\d+)"\s*\/>/', static function (array $m) use ($kept, &$used): string {
        ++$used;

        return $kept[(int) $m[1]] ?? '';
    }, $xml);
    if ($text === null || $used !== count($kept) || str_contains($text, '<x ')) {
        return null;
    }

    return html_entity_decode($text, ENT_XML1 | ENT_QUOTES, 'UTF-8');
}

/**
 * Sends texts to the DeepL API (free endpoint for keys ending in ":fx") and returns the translations in order.
 * DEEPL_API_URL overrides the endpoint (for tests).
 *
 * @param string[] $texts
 *
 * @return string[]
 *
 * @throws RuntimeException when the request fails
 */
function tr_deepl(string $key, array $texts, string $sourceLang, string $targetLang): array
{
    $url = getenv('DEEPL_API_URL') ?: (str_ends_with($key, ':fx') ? 'https://api-free.deepl.com/v2/translate' : 'https://api.deepl.com/v2/translate');
    $body = (string) json_encode([
        'text' => array_values($texts),
        'source_lang' => $sourceLang,
        'target_lang' => $targetLang,
        'tag_handling' => 'xml',
        'ignore_tags' => ['x'],
        'formality' => 'prefer_more',
        'preserve_formatting' => true,
    ], JSON_UNESCAPED_UNICODE | JSON_UNESCAPED_SLASHES);
    $headers = ['Authorization: DeepL-Auth-Key ' . $key, 'Content-Type: application/json'];
    ps_vsecret($key);
    ps_vlog("translations: POST $url (" . count($texts) . " text(s), $sourceLang -> $targetLang, " . strlen($body) . ' bytes, key in the Authorization header)');
    $start = microtime(true);

    if (function_exists('curl_init')) {
        $curl = curl_init($url);
        curl_setopt_array($curl, [
            CURLOPT_POST => true,
            CURLOPT_POSTFIELDS => $body,
            CURLOPT_HTTPHEADER => $headers,
            CURLOPT_RETURNTRANSFER => true,
            CURLOPT_TIMEOUT => 60,
        ]);
        $response = curl_exec($curl);
        $status = (int) curl_getinfo($curl, CURLINFO_HTTP_CODE);
        $error = curl_error($curl);
        if ($response === false) {
            throw new RuntimeException("request failed: $error");
        }
    } else {
        $context = stream_context_create(['http' => ['method' => 'POST', 'header' => implode("\r\n", $headers), 'content' => $body, 'timeout' => 60, 'ignore_errors' => true]]);
        $stream = @fopen($url, 'r', false, $context);
        if ($stream === false) {
            throw new RuntimeException('request failed (no curl, stream could not connect)');
        }
        $meta = stream_get_meta_data($stream);
        $response = (string) stream_get_contents($stream);
        fclose($stream);
        preg_match('#HTTP/\S+\s+(\d{3})#', (string) ($meta['wrapper_data'][0] ?? ''), $m);
        $status = (int) ($m[1] ?? 0);
    }
    ps_vdone("DeepL HTTP $status, " . strlen((string) $response) . ' bytes', $start);
    $data = json_decode((string) $response, true);
    if ($status !== 200 || !is_array($data) || !isset($data['translations'])) {
        $message = is_array($data) && isset($data['message']) ? (string) $data['message'] : substr(trim((string) $response), 0, 200);
        throw new RuntimeException("HTTP $status: $message" . ($status === 403 ? ' (check the key)' : '') . ($status === 456 ? ' (quota exceeded)' : ''));
    }

    return array_map(static fn (array $t): string => (string) ($t['text'] ?? ''), $data['translations']);
}
