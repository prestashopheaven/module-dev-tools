/**
 * Compares the extracted texts with every target catalogue.
 *
 * @param array<string, mixed> $ctx
 * @param array{strings: array<string, array<string, string[]>>} $extraction
 * @param array<string, array{strings: array<string, array<string, array{text: string, machine: ?string}>>, mails: array<string, string>}> $catalogues
 *
 * @return array<string, array{missing: array<int, array{0: string, 1: string}>, machine: array<int, array{0: string, 1: string}>, broken: array<int, array{0: string, 1: string, 2: string}>, obsolete: array<int, array{0: string, 1: string}>}>
 */
function tr_analyse(array $ctx, array $extraction, array $catalogues): array
{
    $result = [];
    foreach ($ctx['targets'] as $iso) {
        $catalogue = $catalogues[$iso];
        $state = ['missing' => [], 'machine' => [], 'broken' => [], 'obsolete' => []];
        foreach ($extraction['strings'] as $domain => $sources) {
            foreach (array_keys($sources) as $source) {
                $entry = $catalogue['strings'][$domain][$source] ?? null;
                if ($entry === null || trim($entry['text']) === '') {
                    $state['missing'][] = [$domain, (string) $source];
                    continue;
                }
                $problem = tr_placeholder_problem((string) $source, $entry['text']);
                if ($problem !== null) {
                    $state['broken'][] = [$domain, (string) $source, $problem];
                }
                if ($entry['machine'] !== null) {
                    $state['machine'][] = [$domain, (string) $source];
                }
            }
        }
        foreach ($catalogue['strings'] as $domain => $entries) {
            foreach (array_keys($entries) as $source) {
                if (!isset($extraction['strings'][$domain][$source])) {
                    $state['obsolete'][] = [$domain, (string) $source];
                }
            }
        }
        $result[$iso] = $state;
        ps_vlog("translations: $iso: " . count($state['missing']) . ' missing, ' . count($state['machine']) . ' machine, '
            . count($state['broken']) . ' broken, ' . count($state['obsolete']) . ' obsolete');
    }

    return $result;
}

/**
 * Checks the translated mail templates: every file of mails/<source>/ exists in mails/<iso>/ for every
 * target language, with the same {variables}, and was translated from the current source version
 * (a SHA-1 of the source file per language in the catalogue).
 *
 * @param array<string, mixed> $ctx
 * @param array<string, array{strings: array<string, array<string, array{text: string, machine: ?string}>>, mails: array<string, string>}> $catalogues
 *
 * @return array{files: string[], problems: array<string, array<int, array{0: string, 1: string}>>, record: array<string, array<string, string>>}
 */
function tr_mails(array $ctx, array $catalogues): array
{
    $sourceDir = $ctx['moduleDir'] . '/mails/' . tr_ps_iso($ctx, $ctx['source']);
    $result = ['files' => [], 'problems' => [], 'record' => []];
    if (!is_dir($sourceDir)) {
        return $result;
    }
    foreach (scandir($sourceDir) ?: [] as $file) {
        if (is_file("$sourceDir/$file") && $file !== 'index.php' && $file[0] !== '.') {
            $result['files'][] = $file;
        }
    }
    foreach ($ctx['targets'] as $iso) {
        $psIso = tr_ps_iso($ctx, $iso);
        $dir = $ctx['moduleDir'] . '/mails/' . $psIso;
        $problems = [];
        foreach ($result['files'] as $file) {
            $source = str_replace("\r\n", "\n", (string) file_get_contents("$sourceDir/$file"));
            $hash = sha1($source);
            if (!is_file("$dir/$file")) {
                $problems[] = ['error', "mails/$psIso/$file is missing: copy mails/{$ctx['source']}/$file and translate it."];
                continue;
            }
            $translated = str_replace("\r\n", "\n", (string) file_get_contents("$dir/$file"));
            preg_match_all('/\{[A-Za-z0-9_]+\}/', $source, $a);
            preg_match_all('/\{[A-Za-z0-9_]+\}/', $translated, $b);
            $x = array_unique($a[0]);
            $y = array_unique($b[0]);
            sort($x);
            sort($y);
            if ($x !== $y) {
                $problems[] = ['error', "mails/$psIso/$file has other {variables} than the source: missing " . tr_list(array_diff($x, $y)) . ', extra ' . tr_list(array_diff($y, $x)) . '.'];
            }
            if ($translated === $source && preg_match('/[A-Za-z]{3}/', (string) preg_replace('/\{[A-Za-z0-9_]+\}|<[^>]*>/', '', $source))) {
                $problems[] = ['warning', "mails/$psIso/$file is identical to the source: not translated yet?"];
            }
            $recorded = $catalogues[$iso]['mails'][$file] ?? null;
            if ($recorded === null) {
                $result['record'][$iso][$file] = $hash;
            } elseif ($recorded !== $hash) {
                $problems[] = ['error', "mails/{$ctx['source']}/$file changed after the $iso translation: update mails/$psIso/$file, then run: vendor/bin/ps-module translations mails-ok $iso"];
            }
        }
        foreach (is_dir($dir) ? (scandir($dir) ?: []) : [] as $file) {
            if (is_file("$dir/$file") && $file !== 'index.php' && $file[0] !== '.' && !in_array($file, $result['files'], true)) {
                $problems[] = ['warning', "mails/$psIso/$file has no source in mails/{$ctx['source']}/."];
            }
        }
        if ($problems !== []) {
            $result['problems'][$iso] = $problems;
        }
    }

    return $result;
}

/**
 * The XLF files the module must ship, as relative path => content: one file per domain and language
 * (translations/<locale>/<DomainWithoutDots>.<locale>.xlf), only with valid translations. The source
 * language file contains every text.
 *
 * @param array<string, mixed> $ctx
 * @param array{strings: array<string, array<string, string[]>>} $extraction
 * @param array<string, array{strings: array<string, array<string, array{text: string, machine: ?string}>>, mails: array<string, string>}> $catalogues
 *
 * @return array<string, string>
 */
function tr_expected_files(array $ctx, array $extraction, array $catalogues): array
{
    $files = [];
    $sourceLocale = tr_locale($ctx, $ctx['source']);
    foreach (array_merge([$ctx['source']], $ctx['targets']) as $iso) {
        $locale = tr_locale($ctx, $iso);
        foreach ($extraction['strings'] as $domain => $sources) {
            $units = [];
            foreach (array_keys($sources) as $source) {
                $source = (string) $source;
                if ($iso === $ctx['source']) {
                    $units[$source] = [$source, null];
                    continue;
                }
                $entry = $catalogues[$iso]['strings'][$domain][$source] ?? null;
                if ($entry !== null && trim($entry['text']) !== '' && tr_placeholder_problem($source, $entry['text']) === null
                    && !preg_match('/[\x00-\x08\x0B\x0C\x0E-\x1F]/', $entry['text'])) {
                    $units[$source] = [$entry['text'], $entry['machine']];
                }
            }
            if ($units !== []) {
                $files["translations/$locale/" . str_replace('.', '', $domain) . ".$locale.xlf"] = tr_xlf($domain, $sourceLocale, $locale, $units);
            }
        }
    }
    ksort($files, SORT_STRING);

    return $files;
}

/**
 * Renders one XLIFF 1.2 file in the format of PrestaShop's own translation files. The trans-unit id is
 * md5 of the source, like PrestaShop; machine translations get state="needs-review-translation".
 *
 * @param array<string, array{0: string, 1: ?string}> $units source => [translation, machine engine or null]
 */
function tr_xlf(string $domain, string $sourceLocale, string $targetLocale, array $units): string
{
    $escape = static fn (string $s): string => htmlspecialchars($s, ENT_XML1 | ENT_NOQUOTES, 'UTF-8');
    $xml = "<?xml version=\"1.0\" encoding=\"UTF-8\"?>\n"
        . "<xliff xmlns=\"urn:oasis:names:tc:xliff:document:1.2\" version=\"1.2\">\n"
        . "  <file original=\"$domain\" source-language=\"$sourceLocale\" target-language=\"$targetLocale\" datatype=\"plaintext\">\n"
        . "    <body>\n";
    foreach ($units as $source => [$target, $machine]) {
        $xml .= '      <trans-unit id="' . md5((string) $source) . "\">\n"
            . '        <source>' . $escape((string) $source) . "</source>\n"
            . '        <target' . ($machine !== null ? ' state="needs-review-translation"' : '') . '>' . $escape($target) . "</target>\n"
            . "      </trans-unit>\n";
    }

    return $xml . "    </body>\n  </file>\n</xliff>\n";
}

/**
 * Compares the generated files with the module and, with $write, brings the module up to date: writes changed
 * XLF files, deletes stale ones of this module, adds index.php to new directories and records the source
 * version of newly translated mails.
 *
 * @param array<string, mixed> $ctx
 * @param array{strings: array<string, array<string, string[]>>} $extraction
 * @param array<string, array{strings: array<string, array<string, array{text: string, machine: ?string}>>, mails: array<string, string>}> $catalogues
 *
 * @return string[] the changes (made, or needed when $write is false)
 */
function tr_build(array $ctx, array $extraction, array $catalogues, bool $write): array
{
    $moduleDir = $ctx['moduleDir'];
    $expected = tr_expected_files($ctx, $extraction, $catalogues);
    $changes = [];
    $index = is_file("$moduleDir/index.php") ? (string) file_get_contents("$moduleDir/index.php") : null;

    $dirs = ['translations'];
    foreach (array_keys($expected) as $file) {
        $dirs[] = dirname($file);
    }
    foreach (array_unique($dirs) as $dir) {
        if (!is_file("$moduleDir/$dir/index.php")) {
            $changes[] = "create $dir/index.php";
            if ($write) {
                if ($index === null) {
                    fwrite(STDERR, "No index.php in the module root to copy into $dir/ (STR-03).\n");
                    continue;
                }
                if (!is_dir("$moduleDir/$dir")) {
                    mkdir("$moduleDir/$dir", 0775, true);
                }
                file_put_contents("$moduleDir/$dir/index.php", $index);
            }
        }
    }
    foreach ($expected as $file => $content) {
        $current = is_file("$moduleDir/$file") ? str_replace("\r\n", "\n", (string) file_get_contents("$moduleDir/$file")) : null;
        if ($current !== $content) {
            $changes[] = ($current === null ? 'create ' : 'update ') . $file;
            if ($write) {
                file_put_contents("$moduleDir/$file", $content);
            }
        }
    }
    // Stale XLF files of this module (texts or languages that are gone).
    foreach (glob("$moduleDir/translations/*/Modules{$ctx['class']}*.xlf") ?: [] as $path) {
        $file = substr(str_replace('\\', '/', $path), strlen($moduleDir) + 1);
        if (!isset($expected[$file])) {
            $changes[] = "delete $file";
            if ($write) {
                unlink($path);
                $dir = dirname($path);
                $left = array_diff(scandir($dir) ?: [], ['.', '..', 'index.php']);
                if ($left === [] && preg_match('/^[a-z]{2,3}-[A-Z]{2}$/', basename($dir))) {
                    @unlink("$dir/index.php");
                    rmdir($dir);
                }
            }
        }
    }
    $mails = tr_mails($ctx, $catalogues);
    foreach ($mails['record'] as $iso => $hashes) {
        $changes[] = "record the mail source version for $iso (" . implode(', ', array_keys($hashes)) . ')';
        if ($write) {
            $catalogue = tr_load_catalogue($ctx, $iso);
            $catalogue['mails'] = $hashes + $catalogue['mails'];
            tr_save_catalogue($ctx, $iso, $catalogue);
        }
    }
    ps_vlog('translations: build ' . ($write ? '' : '(dry run) ') . count($expected) . ' XLF file(s) expected, ' . count($changes) . ' change(s)'
        . ($changes !== [] ? ":\n  " . implode("\n  ", $changes) : ''));

    return $changes;
}

/**
 * Runs the build after a catalogue change and prints what it did.
 *
 * @param array<string, mixed> $ctx
 */
function tr_rebuild(array $ctx): void
{
    $changes = tr_build($ctx, tr_extract($ctx), tr_load_all($ctx), true);
    echo $changes === [] ? "XLF files are up to date.\n" : 'Built: ' . count($changes) . " change(s) in translations/.\n";
}

