/*
 * Translations of a module in every language of <repo>/i18n.json.
 *
 *   ps-module translations extract [--json]       texts per domain; calls PrestaShop cannot extract are errors
 *   ps-module translations status [--json]        what is missing, unreviewed or broken, per language
 *   ps-module translations todo [<iso>...] [--with-machine] [--out=<file>]
 *                                                  JSON skeleton of the missing texts, to fill in and apply
 *                                                  (file paths are relative to the module directory)
 *   ps-module translations apply <file> [--machine=<engine>]
 *                                                  merge a filled-in todo file into the catalogues, then build
 *   ps-module translations fill                   fill missing texts from the shared glossary, then build
 *   ps-module translations auto [<iso>...]        fill missing texts with DeepL (DEEPL_API_KEY), marked "machine"
 *   ps-module translations accept <iso>...|all    mark machine translations as reviewed
 *   ps-module translations prune                  remove catalogue texts that are no longer in the code
 *   ps-module translations mails-ok <iso>...|all  confirm mails/<iso>/ is translated from the current mails/en/
 *   ps-module translations build                  write translations/<locale>/<Domain>.<locale>.xlf + index.php
 *   ps-module translations check                  fails on missing/broken/unbuilt translations (composer checks)
 *
 * Files:
 *   <repo>/i18n.json          source language and enabled languages (ISO codes of resources/languages.json)
 *   <repo>/i18n/<iso>.json    catalogue per language: domain -> English text -> translation. Edited by
 *                             people and Claude; a value {"text": ..., "machine": "deepl"} is unreviewed.
 *   <module>/translations/<locale>/Modules<Module><Part>.<locale>.xlf
 *                             generated by "build"; this is what PrestaShop 8 and 9 load
 *                             (TranslatorLanguageLoader::loadModuleTranslations)
 *   <module>/mails/<iso>/     translated mail templates (PrestaShop ISO code), one per mails/en/ file
 *
 * A call that deliberately passes a dynamic text (e.g. a key that another module put in a hook
 * result) gets a comment with "translations-ignore" and the reason: in PHP on the same line or
 * before the statement, in Smarty and Twig on the same or the previous line.
 */

declare(strict_types=1);

require_once __DIR__ . '/dod.php';
require_once __DIR__ . '/verbose.php';

/** Comment marker that excludes the call on the same or the next line from extraction. */
const TR_IGNORE_MARKER = 'translations-ignore';

/** Directories that are never scanned for texts. */
const TR_SKIP_DIRS = ['vendor', 'tests', '.cache', 'node_modules', 'dist', '.git', '.idea', '.github', 'translations'];

/** Symfony-style placeholders, the same pattern PrestaShop's translator uses ("%count%"). */
const TR_CLASSIC = '/%\w+%/';

/**
 * sprintf placeholders as PrestaShop's translator detects them, without the space flag,
 * so that "10% off" does not count as a placeholder.
 */
const TR_SPRINTF = '/%(?:\d+\$)?[+-]?(?:0|\'.)?-?\d*(?:\.\d+)?[bcdeufFosxX]/';

$argvRest = array_slice($argv, 1);
$moduleDir = dod_norm((string) array_shift($argvRest));
if ($moduleDir === '' || !is_file($moduleDir . '/' . basename($moduleDir) . '.php')) {
    fwrite(STDERR, "Usage: php translations.php <module-dir> <command> [args]\n");
    exit(2);
}
$command = (string) (array_shift($argvRest) ?? 'help');
$options = [];
$positional = [];
foreach ($argvRest as $arg) {
    if (preg_match('/^--([a-z-]+)(?:=(.*))?$/', $arg, $m)) {
        $options[$m[1]] = $m[2] ?? true;
    } else {
        $positional[] = $arg;
    }
}

$ctx = tr_context($moduleDir);
ps_vlog("translations: $command" . ($positional !== [] ? ' ' . implode(' ', $positional) : '') . " for {$ctx['name']}, domains {$ctx['prefix']}*, source {$ctx['source']}, "
    . count($ctx['targets']) . ' target language(s): ' . implode(' ', $ctx['targets']) . ' (' . ($ctx['hasI18n'] ? "{$ctx['repoDir']}/i18n.json" : 'no i18n.json: source language only') . "), catalogues in {$ctx['catalogueDir']}");

exit(match ($command) {
    'extract' => tr_cmd_extract($ctx, $options),
    'status' => tr_cmd_status($ctx, $options),
    'todo' => tr_cmd_todo($ctx, $positional, $options),
    'apply' => tr_cmd_apply($ctx, $positional, $options),
    'fill' => tr_cmd_fill($ctx),
    'auto' => tr_cmd_auto($ctx, $positional),
    'accept' => tr_cmd_accept($ctx, $positional),
    'prune' => tr_cmd_prune($ctx),
    'mails-ok' => tr_cmd_mails_ok($ctx, $positional),
    'build' => tr_cmd_build($ctx),
    'check' => tr_cmd_check($ctx),
    default => tr_help($command),
});

