/*
 * Module context file: <repo>/CONTEXT.md, imported by the repo's CLAUDE.md so Claude reads it at the
 * start of every session instead of searching the code again.
 *
 * Two parts:
 *  - "Notes": written and kept up to date by Claude (purpose, architecture, decisions, pitfalls,
 *    open points, recent changes).
 *  - The generated overview between the markers: identity, definition (hooks, configuration, tabs),
 *    code map with one-line summaries, routes, services, controllers, templates, database,
 *    translations, mails, tests and docs. Only facts from the code, no dates, so it changes only
 *    when the code changes.
 *
 * Usage (from bin/ps-module, cwd = repo):
 *   php context.php <moduleDir>               regenerate + record that the notes match this code
 *   php context.php <moduleDir> --no-notes    same, when the change needs no new notes
 *   php context.php <moduleDir> --generate    regenerate only (what the Stop hook does)
 *   php context.php <moduleDir> --status      is the context current?
 *
 * The Stop hook of the MODULES project regenerates the overview itself and asks Claude to update the
 * notes when the code changed since they were last recorded.
 */

declare(strict_types=1);

require_once __DIR__ . '/dod.php';
require_once __DIR__ . '/verbose.php';

const CONTEXT_BEGIN = '<!-- ps-module:context:begin (generated by `vendor/bin/ps-module context`; do not edit by hand) -->';
const CONTEXT_END = '<!-- ps-module:context:end -->';

if (realpath((string) ($_SERVER['SCRIPT_FILENAME'] ?? '')) === __FILE__) {
    exit(context_cli(array_slice($argv, 1)));
}

/**
 * Command line entry: regenerate, record, or report the state of CONTEXT.md.
 *
 * @param string[] $args module directory followed by options
 */
function context_cli(array $args): int
{
    $moduleDir = dod_norm((string) array_shift($args));
    $repoDir = dod_repo_dir($moduleDir);
    if ($repoDir === null) {
        fwrite(STDERR, "ps-module context: no module.spec.json found above $moduleDir.\n");

        return 2;
    }
    if (in_array('--status', $args, true)) {
        $state = context_state($repoDir);
        echo 'CONTEXT.md: ' . ($state['exists'] ? 'present' : 'missing')
            . ', overview ' . ($state['generated_current'] ? 'current' : 'outdated')
            . ', notes ' . ($state['notes_current'] ? 'match the current code' : 'not updated since the last code change') . "\n";

        return $state['exists'] && $state['generated_current'] && $state['notes_current'] ? 0 : 1;
    }

    $changed = context_write($repoDir);
    if (in_array('--generate', $args, true)) {
        echo 'ps-module context: overview ' . ($changed ? 'updated' : 'already current') . " in CONTEXT.md.\n";

        return 0;
    }

    $record = context_record($repoDir);
    $notesHash = context_notes_hash((string) file_get_contents("$repoDir/CONTEXT.md"));
    $codeChanged = ($record['fingerprint'] ?? '') !== dod_fingerprint($repoDir);
    ps_vlog('context: last record ' . ($record === [] ? 'none' : 'code ' . substr((string) ($record['fingerprint'] ?? ''), 0, 12) . ', notes ' . substr((string) ($record['notes'] ?? ''), 0, 12))
        . '; code ' . ($codeChanged ? 'changed' : 'unchanged') . ', notes ' . (($record['notes'] ?? '') === $notesHash ? 'unchanged' : 'changed') . ' (' . substr($notesHash, 0, 12) . ')'
        . (in_array('--no-notes', $args, true) ? ', --no-notes' : ''));
    if ($codeChanged && ($record['notes'] ?? '') === $notesHash && !in_array('--no-notes', $args, true)) {
        echo "ps-module context: the code changed but the Notes in CONTEXT.md did not.\n"
            . "  Update the Notes (at least 'Recent changes'; also purpose, architecture, decisions, pitfalls or\n"
            . "  open points when they changed) and run this again, or run it with --no-notes when the change\n"
            . "  really needs no note.\n";

        return 1;
    }
    context_save_record($repoDir, $notesHash);
    echo 'ps-module context: CONTEXT.md ' . ($changed ? 'overview updated' : 'overview current') . ", notes recorded for the current code.\n";

    return 0;
}

