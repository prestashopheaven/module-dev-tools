/**
 * Where the record of the last notes update is kept (not in git).
 */
function context_record_file(string $repoDir): string
{
    return dod_norm($repoDir) . '/.cache/dod/context.json';
}

/**
 * Reads the record of the last notes update: source fingerprint and notes hash.
 *
 * @return array{fingerprint?: string, notes?: string}
 */
function context_record(string $repoDir): array
{
    $file = context_record_file($repoDir);
    $data = is_file($file) ? json_decode((string) file_get_contents($file), true) : null;

    return is_array($data) ? $data : [];
}

/**
 * Records that the notes match the current code.
 */
function context_save_record(string $repoDir, string $notesHash): void
{
    $file = context_record_file($repoDir);
    if (!is_dir(dirname($file))) {
        @mkdir(dirname($file), 0775, true);
    }
    file_put_contents($file, json_encode([
        'fingerprint' => dod_fingerprint($repoDir),
        'notes' => $notesHash,
        'time' => date('c'),
    ], JSON_PRETTY_PRINT | JSON_UNESCAPED_SLASHES) . "\n");
    ps_vlog("context: notes recorded for the current code in $file");
}

/**
 * Hash of the Notes part (everything outside the generated block), whitespace-normalised.
 */
function context_notes_hash(string $content): string
{
    $notes = (string) preg_replace('/' . preg_quote(CONTEXT_BEGIN, '/') . '.*?' . preg_quote(CONTEXT_END, '/') . '/s', '', $content);

    return hash('sha256', (string) preg_replace('/\s+/', ' ', trim($notes)));
}

/**
 * Is CONTEXT.md present, is its overview current, and were the notes recorded for the current code?
 *
 * @return array{exists: bool, generated_current: bool, notes_current: bool}
 */
function context_state(string $repoDir): array
{
    $file = dod_norm($repoDir) . '/CONTEXT.md';
    if (!is_file($file)) {
        return ['exists' => false, 'generated_current' => false, 'notes_current' => false];
    }
    $content = (string) file_get_contents($file);
    $current = str_contains($content, CONTEXT_BEGIN . "\n" . context_generate($repoDir) . CONTEXT_END);
    $record = context_record($repoDir);
    ps_vlog('context: overview in ' . $file . ' ' . ($current ? 'matches' : 'differs from') . ' a fresh generation; notes recorded for code '
        . substr((string) ($record['fingerprint'] ?? 'never'), 0, 12) . ' (' . ($record['time'] ?? 'no record') . ')');

    return [
        'exists' => true,
        'generated_current' => $current,
        'notes_current' => ($record['fingerprint'] ?? '') === dod_fingerprint($repoDir),
    ];
}

/**
 * Writes CONTEXT.md: creates it with an empty Notes skeleton when missing, otherwise replaces only
 * the generated block. Returns true when the file changed.
 */
function context_write(string $repoDir): bool
{
    $repoDir = dod_norm($repoDir);
    $file = "$repoDir/CONTEXT.md";
    $block = CONTEXT_BEGIN . "\n" . context_generate($repoDir) . CONTEXT_END;
    $old = is_file($file) ? (string) file_get_contents($file) : '';
    if ($old === '') {
        $new = context_skeleton($repoDir) . "\n" . $block . "\n";
    } elseif (str_contains($old, CONTEXT_BEGIN) && str_contains($old, CONTEXT_END)) {
        $new = (string) preg_replace_callback(
            '/' . preg_quote(CONTEXT_BEGIN, '/') . '.*?' . preg_quote(CONTEXT_END, '/') . '/s',
            static fn (): string => $block,
            $old,
            1
        );
    } else {
        $new = rtrim($old) . "\n\n" . $block . "\n";
    }
    $new = str_replace("\r\n", "\n", $new);
    if ($new === str_replace("\r\n", "\n", $old)) {
        ps_vlog("context: $file unchanged");

        return false;
    }
    file_put_contents($file, $new);
    ps_vlog("context: $file " . ($old === '' ? 'created with an empty Notes skeleton' : 'generated block replaced') . ' (' . strlen($new) . ' bytes)');

    return true;
}

/**
 * The initial CONTEXT.md text above the generated block: title, how to use it, and the Notes headings.
 */
function context_skeleton(string $repoDir): string
{
    $spec = context_spec($repoDir);
    $title = ($spec['display_name'] ?? '') !== '' ? "{$spec['display_name']} (`{$spec['module_name']}`)" : basename($repoDir);
    $description = (string) ($spec['description'] ?? '');

    return <<<MD
# Context: $title

$description

Read this file first; search the code only for details that are not here. The Notes are kept up to
date by Claude after every change (conventions CTX-01..04); the overview at the bottom is generated
from the code by `vendor/bin/ps-module context` and refreshed by the Stop hook.

## Notes (maintained by Claude)

### Purpose and behaviour
- TODO: what the module does for the merchant and the customer, in a few lines.

### Architecture and data flow
- TODO: the main path through the code (hook → service → repository → template), where state lives.

### Decisions
- TODO: choices with their reason (why this hook, why AJAX, why this table layout).

### Pitfalls and known issues
- None yet.

### Open points
- None yet.

### Recent changes
- Initial version.

MD;
}

