/**
 * Directories of the module repos of the workspace: modules/<repo> (the layout since October 2026) and, for older
 * layouts, <repo> directly in the workspace (not libraries/, modules/ or demo-site/).
 *
 * @return string[]
 */
function context_module_repos(string $projectDir): array
{
    $repos = glob($projectDir . '/modules/*', GLOB_ONLYDIR) ?: [];
    foreach (glob($projectDir . '/*', GLOB_ONLYDIR) ?: [] as $dir) {
        if (!in_array(basename($dir), ['libraries', 'modules', 'demo-site', 'docs', 'branding'], true)) {
            $repos[] = $dir;
        }
    }

    return array_map(static fn (string $dir): string => str_replace('\\', '/', $dir), $repos);
}

/**
 * Overview of a workspace with several module repos (e.g. MODULES/): every module with its version,
 * description, features and languages, the shared packages with their versions, and where the skill
 * lives. Deterministic, so the file only changes when a module or package changes.
 */
function context_workspace(string $projectDir): string
{
    $projectDir = dod_norm($projectDir);
    $out = [
        '# Workspace context (generated)',
        '',
        'Generated by the Stop hook from the module repos and packages below; do not edit. Each module repo has',
        'its own `CONTEXT.md` (imported by its `CLAUDE.md`) with notes and a code overview: read that first.',
        '',
        '## Modules',
        '',
        '| Repo | Module | Version | PrestaShop | Languages | Features | Description |',
        '|---|---|---|---|---|---|---|',
    ];
    $modules = 0;
    foreach (context_module_repos($projectDir) as $repo) {
        $repo = dod_norm($repo);
        $moduleDir = is_file("$repo/module.spec.json") ? dod_module_dir($repo) : null;
        if ($moduleDir === null) {
            continue;
        }
        $spec = context_spec($repo);
        $name = basename($moduleDir);
        $main = (string) @file_get_contents("$moduleDir/$name.php");
        $version = preg_match('/\$this->version\s*=\s*[\'"]([^\'"]+)/', $main, $m) ? $m[1] : '?';
        $min = preg_match("/'min'\s*=>\s*'([^']+)'/", $main, $mm) ? $mm[1] : '?';
        $max = preg_match("/'max'\s*=>\s*'([^']+)'/", $main, $mx) ? $mx[1] : '?';
        $i18n = is_file("$repo/i18n.json") ? (array) (json_decode((string) file_get_contents("$repo/i18n.json"), true)['languages'] ?? []) : [];
        $out[] = '| `' . basename($repo) . "` | `$name` " . (string) ($spec['display_name'] ?? '') . " | $version | $min – $max | "
            . ($i18n === [] ? '—' : count($i18n)) . ' | ' . implode(', ', (array) ($spec['features'] ?? [])) . ' | '
            . str_replace('|', '/', (string) ($spec['description'] ?? '')) . ' |';
        ++$modules;
    }
    if ($modules === 0) {
        $out[] = '| — | | | | | | |';
    }
    $out[] = '';
    $out[] = 'Repos without `module.spec.json` (older modules) are not listed; they follow the conventions where their tooling allows.';
    $out[] = '';
    $out[] = '## Shared packages (`libraries/`, on Packagist)';
    $out[] = '';
    foreach (glob($projectDir . '/libraries/*/composer.json') ?: [] as $composer) {
        $data = json_decode((string) file_get_contents($composer), true);
        if (is_array($data)) {
            $out[] = '- `' . (string) ($data['name'] ?? '?') . '` ' . (string) ($data['version'] ?? '?') . ': ' . (string) ($data['description'] ?? '');
        }
    }
    $out[] = '';
    $out[] = '## Where things are';
    $out[] = '';
    $out[] = '- New module: `/ps-module <idea>` (skill in `.claude/skills/ps-module/`: SKILL.md, interview.md, conventions.md, validator-rules.md, features/, templates/, research/).';
    $out[] = '- Definition of done and its enforcement: `.claude/hooks/module-dod-check.php` (Stop hook), stamps in `<repo>/.cache/dod/`.';
    $out[] = '- Secrets: `.env` here (validator API key, Packagist, optional DeepL). Never print or commit.';
    $out[] = '';

    return implode("\n", $out);
}
