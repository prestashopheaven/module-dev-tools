/**
 * module.spec.json of the repository (empty array when missing).
 *
 * @return array<string, mixed>
 */
function context_spec(string $repoDir): array
{
    $file = dod_norm($repoDir) . '/module.spec.json';
    $spec = is_file($file) ? json_decode((string) file_get_contents($file), true) : null;

    return is_array($spec) ? $spec : [];
}

/**
 * Builds the generated overview (markdown, ends with a newline). Deterministic: same code, same text.
 */
function context_generate(string $repoDir): string
{
    $repoDir = dod_norm($repoDir);
    $moduleDir = dod_module_dir($repoDir);
    if ($moduleDir === null) {
        return "_No module directory found._\n";
    }
    $name = basename($moduleDir);
    $files = context_files($moduleDir);
    $php = array_values(array_filter($files, static fn (string $f): bool => str_ends_with($f, '.php') && basename($f) !== 'index.php'));
    $classes = [];
    foreach ($php as $file) {
        foreach (context_parse_php("$moduleDir/$file") as $class) {
            $class['file'] = $file;
            $classes[] = $class;
        }
    }
    $definition = context_definition($moduleDir);
    ps_vlog('context: ' . count($files) . ' file(s) in the module, ' . count($php) . ' PHP file(s), ' . count($classes) . ' class(es)/trait(s)/interface(s)/enum(s); definition from '
        . ($definition['source'] !== '' ? $definition['source'] : 'nothing (no src/Install/ModuleDefinition.php)') . ': ' . count($definition['hooks']) . ' hook(s), '
        . count($definition['configuration']) . ' setting(s), ' . count($definition['tabs']) . ' tab(s)');

    $out = [];
    $out[] = '## Overview (generated)';
    $out[] = '';
    $out = array_merge($out, context_section_identity($repoDir, $moduleDir, $name));
    $out = array_merge($out, context_section_definition($definition, $classes));
    $out = array_merge($out, context_section_code($classes));
    $out = array_merge($out, context_section_symfony($moduleDir));
    $out = array_merge($out, context_section_views($files));
    $out = array_merge($out, context_section_database($moduleDir, $files));
    $out = array_merge($out, context_section_translations($repoDir, $moduleDir, $files));
    $out = array_merge($out, context_section_docs($repoDir));
    $out[] = '### Commands';
    $out[] = '`composer verify` (definition of done) · `vendor/bin/ps-module status` · `ps-module translations status` · `ps-module docs status` · `ps-module shops run` · `ps-module context` (after updating the Notes)';
    $out[] = '';

    return implode("\n", $out);
}

/**
 * Module files relative to the module directory, sorted, without vendor, caches and generated output.
 *
 * @return string[]
 */
function context_files(string $moduleDir): array
{
    $skip = ['vendor', '.cache', 'node_modules', '.git', '.idea', 'dist'];
    $it = new RecursiveIteratorIterator(new RecursiveCallbackFilterIterator(
        new RecursiveDirectoryIterator($moduleDir, FilesystemIterator::SKIP_DOTS),
        static fn (SplFileInfo $f): bool => !($f->isDir() && in_array($f->getFilename(), $skip, true))
    ));
    $files = [];
    foreach ($it as $file) {
        $files[] = substr(str_replace('\\', '/', $file->getPathname()), strlen($moduleDir) + 1);
    }
    sort($files);

    return $files;
}

/**
 * Classes, traits, interfaces and enums in a PHP file, with the first sentence of their docblock and
 * their methods (public ones for classes; all for traits, because the module class gets them).
 *
 * @return array<int, array{kind: string, name: string, fqcn: string, summary: string, methods: string[], extends: string}>
 */
function context_parse_php(string $path): array
{
    $tokens = token_get_all((string) file_get_contents($path));
    $namespace = '';
    $result = [];
    $doc = '';
    $current = null;
    $depth = 0;
    $classDepth = -1;
    $visibility = [];
    $count = count($tokens);
    for ($i = 0; $i < $count; ++$i) {
        $t = $tokens[$i];
        if (is_string($t)) {
            if ($t === '{' || $t === '}' || $t === ')') {
                $visibility = []; // promoted constructor parameters carry their own visibility
            }
            if ($t === '{') {
                ++$depth;
            } elseif ($t === '}') {
                --$depth;
                if ($current !== null && $depth === $classDepth) {
                    $result[] = $current;
                    $current = null;
                    $classDepth = -1;
                }
            } elseif ($t === ';' || $t === '=') {
                $visibility = [];
                $doc = '';
            }
            continue;
        }
        [$id, $text] = $t;
        if ($id === T_DOC_COMMENT) {
            $doc = $text;
        } elseif ($id === T_NAMESPACE) {
            $namespace = '';
            for ($j = $i + 1; $j < $count && $tokens[$j] !== ';' && $tokens[$j] !== '{'; ++$j) {
                $namespace .= is_array($tokens[$j]) && $tokens[$j][0] !== T_WHITESPACE ? $tokens[$j][1] : '';
            }
        } elseif ($id === T_CURLY_OPEN || $id === T_DOLLAR_OPEN_CURLY_BRACES) {
            ++$depth;
        } elseif (in_array($id, [T_CLASS, T_TRAIT, T_INTERFACE], true) || (defined('T_ENUM') && $id === T_ENUM)) {
            // Skip "::class" and anonymous classes.
            $prev = context_prev_token($tokens, $i);
            $next = context_next_token($tokens, $i);
            if ($prev === T_DOUBLE_COLON || $prev === T_NEW || !is_array($tokens[$next] ?? null) || $tokens[$next][0] !== T_STRING) {
                continue;
            }
            $extends = '';
            for ($j = $next + 1; $j < $count && $tokens[$j] !== '{'; ++$j) {
                if (is_array($tokens[$j]) && $tokens[$j][0] === T_EXTENDS) {
                    $k = context_next_token($tokens, $j);
                    $extends = is_array($tokens[$k]) ? ltrim($tokens[$k][1], '\\') : '';
                    break;
                }
            }
            $kind = strtolower($text);
            $current = [
                'kind' => $kind,
                'name' => $tokens[$next][1],
                'fqcn' => ltrim($namespace . '\\' . $tokens[$next][1], '\\'),
                'summary' => context_summary($doc),
                'methods' => [],
                'extends' => $extends,
            ];
            $classDepth = $depth;
            $doc = '';
        } elseif (in_array($id, [T_PUBLIC, T_PROTECTED, T_PRIVATE, T_STATIC, T_ABSTRACT, T_FINAL], true)) {
            $visibility[] = $id;
        } elseif ($id === T_FUNCTION && $current !== null && $depth === $classDepth + 1) {
            $k = context_next_token($tokens, $i);
            if (is_array($tokens[$k] ?? null) && $tokens[$k][0] === T_STRING) {
                $public = !in_array(T_PRIVATE, $visibility, true) && !in_array(T_PROTECTED, $visibility, true);
                if ($public || $current['kind'] === 'trait') {
                    $current['methods'][] = $tokens[$k][1];
                }
            }
            $visibility = [];
            $doc = '';
        } elseif (!in_array($id, [T_WHITESPACE, T_COMMENT, T_ATTRIBUTE, T_READONLY], true)) {
            // Any other code between a docblock and a class means the docblock was not the class's
            // (e.g. the license header above declare/namespace/use).
            $doc = '';
        }
    }

    return $result;
}

/**
 * Index of the previous non-whitespace token's id (or 0).
 *
 * @param array<int, mixed> $tokens
 */
function context_prev_token(array $tokens, int $i): int
{
    for ($j = $i - 1; $j >= 0; --$j) {
        if (is_array($tokens[$j]) && in_array($tokens[$j][0], [T_WHITESPACE, T_COMMENT, T_DOC_COMMENT], true)) {
            continue;
        }

        return is_array($tokens[$j]) ? (int) $tokens[$j][0] : 0;
    }

    return 0;
}

/**
 * Index of the next token that is not whitespace or a comment.
 *
 * @param array<int, mixed> $tokens
 */
function context_next_token(array $tokens, int $i): int
{
    $count = count($tokens);
    for ($j = $i + 1; $j < $count; ++$j) {
        if (is_array($tokens[$j]) && in_array($tokens[$j][0], [T_WHITESPACE, T_COMMENT, T_DOC_COMMENT], true)) {
            continue;
        }

        return $j;
    }

    return $count;
}

/**
 * First sentence of a docblock (without tags), max. 140 characters.
 */
function context_summary(string $doc): string
{
    $lines = preg_split('/\R/', $doc) ?: [];
    $text = '';
    foreach ($lines as $line) {
        $line = trim((string) preg_replace('#^\s*/?\*+/?#', '', $line));
        if ($line === '' && $text !== '') {
            break;
        }
        if (str_starts_with($line, '@')) {
            break;
        }
        $text .= ($text === '' ? '' : ' ') . $line;
    }
    $text = trim($text);
    if (preg_match('/^(.+?[.!?])(\s|$)/', $text, $m)) {
        $text = $m[1];
    }

    return mb_strlen($text) > 140 ? rtrim(mb_substr($text, 0, 137)) . '...' : $text;
}

/**
 * The module definition (hooks, configuration, generated keys, tabs), read with reflection in a
 * separate PHP process (the module's own autoloader), or with a text fallback without vendor/.
 *
 * @return array{hooks: string[], configuration: array<string, mixed>, generated: string[], tabs: array<int, array<string, mixed>>, source: string}
 */
function context_definition(string $moduleDir): array
{
    $empty = ['hooks' => [], 'configuration' => [], 'generated' => [], 'tabs' => [], 'source' => ''];
    $file = "$moduleDir/src/Install/ModuleDefinition.php";
    if (!is_file($file)) {
        return $empty;
    }
    if (is_file("$moduleDir/vendor/autoload.php")) {
        // A separate process: the definition needs the module's autoloader, and a fatal error must not stop us.
        $probe = (string) tempnam(sys_get_temp_dir(), 'psctx');
        file_put_contents($probe, '<?php define("_PS_VERSION_", "9.0.0"); require ' . var_export("$moduleDir/vendor/autoload.php", true) . '; require_once ' . var_export($file, true) . ';'
            . ' foreach (get_declared_classes() as $c) { if (str_ends_with($c, "\\\\Install\\\\ModuleDefinition")) { $r = new ReflectionClass($c);'
            . ' echo json_encode(["hooks" => $r->getConstant("HOOKS") ?: [], "configuration" => $r->getConstant("CONFIGURATION") ?: [],'
            . ' "generated" => $r->getConstant("GENERATED_CONFIGURATION") ?: [], "tabs" => $r->getConstant("TABS") ?: []]); break; } }');
        $command = escapeshellarg(PHP_BINARY) . ' ' . escapeshellarg($probe) . ' 2>' . (PHP_OS_FAMILY === 'Windows' ? 'NUL' : '/dev/null');
        ps_vcmd($command . '   (reads ModuleDefinition with the module autoloader)', (string) getcwd());
        $start = microtime(true);
        $output = (string) shell_exec($command);
        ps_vdone('definition probe', $start);
        @unlink($probe);
        $data = json_decode($output, true);
        if (!is_array($data)) {
            ps_vlog('context: probe gave no JSON (' . ($output !== '' ? substr(trim($output), 0, 300) : 'no output') . '): reading the constants as text');
        }
        if (is_array($data)) {
            return [
                'hooks' => array_values(array_map('strval', (array) $data['hooks'])),
                'configuration' => (array) $data['configuration'],
                'generated' => array_values(array_map('strval', (array) $data['generated'])),
                'tabs' => array_values((array) $data['tabs']),
                'source' => 'reflection',
            ];
        }
    }
    // Fallback: string literals inside the constant arrays.
    $code = (string) file_get_contents($file);
    $consts = [];
    preg_match_all("/const\\s+(\\w+)\\s*=\\s*'([^']*)'\\s*;/", $code, $m, PREG_SET_ORDER);
    foreach ($m as $c) {
        $consts['self::' . $c[1]] = $c[2];
    }
    $block = static function (string $const) use ($code): string {
        return preg_match('/const\s+' . $const . '\s*=\s*\[(.*?)\];/s', $code, $b) ? $b[1] : '';
    };
    $result = $empty;
    $result['source'] = 'text';
    preg_match_all("/'([^']+)'/", $block('HOOKS'), $h);
    $result['hooks'] = $h[1];
    preg_match_all("/(self::\\w+|'[^']+')\\s*=>\\s*([^,\\n]+)/", $block('CONFIGURATION'), $c, PREG_SET_ORDER);
    foreach ($c as $pair) {
        $key = $consts[$pair[1]] ?? trim($pair[1], "'");
        $result['configuration'][$key] = trim($pair[2]);
    }
    preg_match_all("/(self::\\w+|'[^']+')/", $block('GENERATED_CONFIGURATION'), $g);
    $result['generated'] = array_map(static fn (string $k): string => $consts[$k] ?? trim($k, "'"), $g[1]);

    return $result;
}

/**
 * Identity: names, versions, compatibility, languages, features, releases.
 *
 * @return string[]
 */
function context_section_identity(string $repoDir, string $moduleDir, string $name): array
{
    $spec = context_spec($repoDir);
    $main = (string) @file_get_contents("$moduleDir/$name.php");
    $get = static fn (string $prop): string => preg_match('/\$this->' . $prop . '\s*=\s*[\'"]([^\'"]*)[\'"]/', $main, $m) ? $m[1] : '?';
    preg_match("/'min'\\s*=>\\s*'([^']+)'/", $main, $min);
    preg_match("/'max'\\s*=>\\s*([^,\\]\\n]+)/", $main, $max);
    preg_match_all('/^\s*use\s+(\w+)(?:\s*,\s*(\w+))*\s*[;{]/m', $main, $traits);
    $i18n = is_file("$repoDir/i18n.json") ? (array) (json_decode((string) file_get_contents("$repoDir/i18n.json"), true)['languages'] ?? []) : [];
    $tags = [];
    if (is_dir("$repoDir/.git")) {
        $command = 'git -C ' . escapeshellarg($repoDir) . ' tag --list "v*" --sort=-v:refname 2>' . (PHP_OS_FAMILY === 'Windows' ? 'NUL' : '/dev/null');
        ps_vcmd($command, (string) getcwd());
        $start = microtime(true);
        $tags = array_filter(preg_split('/\R/', (string) shell_exec($command)) ?: []);
        ps_vdone('git tag: ' . count($tags) . ' release tag(s)', $start);
    }
    $multistore = str_contains($main, 'MULTISTORE_COMPATIBILITY_YES') ? 'Fully (MULTISTORE_COMPATIBILITY_YES)' : 'not declared';

    $rows = [
        'Module' => "`$name` (class `" . ucfirst($name) . '`, namespace `' . (string) ($spec['namespace'] ?? '?') . '`)',
        'Version' => $get('version') . ($tags !== [] ? ' (releases: ' . implode(', ', array_slice($tags, 0, 5)) . ')' : ' (no release tag yet)'),
        'PrestaShop' => trim($min[1] ?? '?') . ' – ' . trim(trim($max[1] ?? '?'), "' "),
        'PHP' => '>= ' . (string) ($spec['php_min'] ?? '?'),
        'Tab / distribution' => $get('tab') . ' / ' . (string) ($spec['distribution'] ?? '?'),
        'Multistore' => $multistore,
        'Languages' => $i18n !== [] ? implode(', ', $i18n) : '—',
        'Features (scaffold)' => ($spec['features'] ?? []) !== [] ? implode(', ', (array) $spec['features']) : '—',
        'Main class traits' => isset($traits[0]) && $traits[0] !== [] ? implode(', ', array_map(static fn (string $u): string => trim((string) preg_replace('/^\s*use\s+|\s*[;{]$/', '', $u)), $traits[0])) : '—',
    ];
    $out = ['### Identity', '', '| | |', '|---|---|'];
    foreach ($rows as $label => $value) {
        $out[] = "| $label | $value |";
    }
    $out[] = '';

    return $out;
}

/**
 * Hooks (with the trait or class that implements them), configuration, generated secrets and tabs.
 *
 * @param array{hooks: string[], configuration: array<string, mixed>, generated: string[], tabs: array<int, array<string, mixed>>, source: string} $definition
 * @param array<int, array{kind: string, name: string, fqcn: string, summary: string, methods: string[], extends: string, file?: string}> $classes
 *
 * @return string[]
 */
function context_section_definition(array $definition, array $classes): array
{
    $implemented = [];
    foreach ($classes as $class) {
        foreach ($class['methods'] as $method) {
            if (preg_match('/^hook(\w+)$/i', $method, $m)) {
                $implemented[strtolower($m[1])] = ($class['file'] ?? $class['name']);
            }
        }
    }
    // Display hooks without a hook method go to renderWidget() when the module is a widget.
    $widget = null;
    foreach ($classes as $class) {
        if (in_array('renderWidget', $class['methods'], true)) {
            $widget = (string) ($class['file'] ?? $class['name']);
        }
    }
    $out = ['### Definition (`src/Install/ModuleDefinition.php`)', ''];
    if ($definition['source'] === '') {
        $out[] = '_No ModuleDefinition: hooks found in code: ' . ($implemented === [] ? 'none' : implode(', ', array_keys($implemented))) . '._';
        $out[] = '';

        return $out;
    }
    $hooks = [];
    foreach ($definition['hooks'] as $hook) {
        $where = $implemented[strtolower($hook)] ?? null;
        if ($where === null && $widget !== null && str_starts_with(strtolower($hook), 'display')) {
            $hooks[] = "`$hook` → widget `$widget`";
            continue;
        }
        $hooks[] = "`$hook`" . ($where !== null ? " → `$where`" : ' **(no hook method found)**');
    }
    foreach ($implemented as $hook => $where) {
        if (!in_array($hook, array_map('strtolower', $definition['hooks']), true)) {
            $hooks[] = "`$hook` → `$where` **(method exists, hook not registered)**";
        }
    }
    $out[] = '- Hooks: ' . ($hooks === [] ? '—' : implode('; ', $hooks));
    $config = [];
    foreach ($definition['configuration'] as $key => $default) {
        $config[] = "`$key` = " . (is_string($default) ? ($definition['source'] === 'text' ? $default : var_export($default, true)) : json_encode($default));
    }
    $out[] = '- Configuration (global defaults): ' . ($config === [] ? '—' : implode('; ', $config));
    $out[] = '- Generated secrets: ' . ($definition['generated'] === [] ? '—' : '`' . implode('`, `', $definition['generated']) . '`');
    $tabs = [];
    foreach ($definition['tabs'] as $tab) {
        $tabs[] = '`' . ($tab['class_name'] ?? '?') . '`' . (($tab['route_name'] ?? '') !== '' ? ' → route `' . $tab['route_name'] . '`' : '')
            . (empty($tab['visible']) ? ' (hidden)' : '') . (($tab['parent_class_name'] ?? '') !== '' ? ' under `' . $tab['parent_class_name'] . '`' : '');
    }
    $out[] = '- Tabs: ' . ($tabs === [] ? '—' : implode('; ', $tabs));
    $out[] = '';

    return $out;
}

/**
 * Code map: every class, trait and interface with its summary and methods, grouped by directory.
 *
 * @param array<int, array{kind: string, name: string, fqcn: string, summary: string, methods: string[], extends: string, file?: string}> $classes
 *
 * @return string[]
 */
function context_section_code(array $classes): array
{
    $out = ['### Code map', ''];
    $byDir = [];
    foreach ($classes as $class) {
        $byDir[dirname((string) ($class['file'] ?? '.'))][] = $class;
    }
    ksort($byDir);
    $tests = [];
    foreach ($byDir as $dir => $list) {
        if (str_starts_with($dir, 'tests')) {
            foreach ($list as $class) {
                $tests[] = $class['name'];
            }
            continue;
        }
        $out[] = "- `$dir/`";
        foreach ($list as $class) {
            $methods = array_values(array_filter($class['methods'], static fn (string $m): bool => $m !== '__construct'));
            $methodText = $methods === [] ? '' : ' — ' . implode(', ', array_slice($methods, 0, 12)) . (count($methods) > 12 ? ', …' : '');
            $kind = $class['kind'] === 'class' ? '' : " ({$class['kind']})";
            $extends = $class['extends'] !== '' && $class['kind'] === 'class' ? ' extends ' . basename(str_replace('\\', '/', $class['extends'])) : '';
            $out[] = "  - `{$class['name']}`$kind$extends: " . ($class['summary'] !== '' ? $class['summary'] : '_no docblock_') . $methodText;
        }
    }
    if ($tests !== []) {
        sort($tests);
        $out[] = '- Tests: ' . implode(', ', $tests);
    }
    $out[] = '';

    return $out;
}

/**
 * Symfony routes and service ids from config/.
 *
 * @return string[]
 */
function context_section_symfony(string $moduleDir): array
{
    $out = [];
    $routesFile = "$moduleDir/config/routes.yml";
    if (is_file($routesFile)) {
        $routes = [];
        $current = null;
        foreach (preg_split('/\R/', (string) file_get_contents($routesFile)) ?: [] as $line) {
            $line = rtrim((string) preg_replace('/\s+#.*$/', '', $line)); // YAML comments
            if (preg_match('/^([A-Za-z0-9_.-]+):\s*$/', $line, $m)) {
                $current = $m[1];
                $routes[$current] = ['path' => '', 'methods' => '', 'controller' => ''];
            } elseif ($current !== null && preg_match('/^\s+path:\s*(.+)$/', $line, $m)) {
                $routes[$current]['path'] = trim($m[1], " '\"");
            } elseif ($current !== null && preg_match('/^\s+methods:\s*(.+)$/', $line, $m)) {
                $routes[$current]['methods'] = trim($m[1], ' []');
            } elseif ($current !== null && preg_match('/^\s+_controller:\s*(.+)$/', $line, $m)) {
                $routes[$current]['controller'] = basename(str_replace('\\', '/', trim($m[1], " '\"")));
            }
        }
        if ($routes !== []) {
            $out[] = '### Routes (`config/routes.yml`)';
            $out[] = '';
            foreach ($routes as $route => $r) {
                $out[] = "- `$route`: " . ($r['methods'] !== '' ? $r['methods'] . ' ' : '') . "`{$r['path']}` → `{$r['controller']}`";
            }
            $out[] = '';
        }
    }
    $services = [];
    foreach (array_merge(glob("$moduleDir/config/*.yml") ?: [], glob("$moduleDir/config/*/*.yml") ?: []) as $yml) {
        if (basename($yml) === 'routes.yml') {
            continue;
        }
        $ids = [];
        $inServices = false;
        foreach (preg_split('/\R/', (string) file_get_contents($yml)) ?: [] as $line) {
            if (preg_match('/^services:\s*$/', $line)) {
                $inServices = true;
            } elseif (preg_match('/^\S/', $line)) {
                $inServices = false;
            } elseif ($inServices && preg_match('/^  ([^\s#_][^:]*):\s*(.*)$/', $line, $m)) {
                $ids[] = trim($m[1], "'\"");
            }
        }
        if ($ids !== []) {
            $services[] = '`' . substr(str_replace('\\', '/', $yml), strlen($moduleDir) + 1) . '`: ' . implode(', ', array_map(static fn (string $id): string => '`' . $id . '`', $ids));
        }
    }
    if ($services !== []) {
        $out[] = '### Services';
        $out[] = '';
        foreach ($services as $line) {
            $out[] = "- $line";
        }
        $out[] = '';
    }

    return $out;
}

/**
 * Controllers, templates, assets, mails and upgrade scripts (file lists per directory).
 *
 * @param string[] $files
 *
 * @return string[]
 */
function context_section_views(array $files): array
{
    $groups = [
        'Front controllers' => '#^controllers/front/[^/]+\.php$#',
        'Admin controllers (legacy)' => '#^controllers/admin/[^/]+\.php$#',
        'Templates' => '#^views/templates/.+\.(tpl|twig)$#',
        'JS / CSS' => '#^views/(js|css)/.+\.(js|css)$#',
        'Mails (en)' => '#^mails/en/[^/]+$#',
        'Upgrade scripts' => '#^upgrade/upgrade-[\d.]+\.php$#',
        'Overrides' => '#^override/.+\.php$#',
    ];
    $out = ['### Files', ''];
    foreach ($groups as $label => $regex) {
        $list = array_values(array_filter($files, static fn (string $f): bool => (bool) preg_match($regex, $f) && basename($f) !== 'index.php'));
        if ($list !== []) {
            $out[] = "- $label: " . implode(', ', array_map(static fn (string $f): string => "`$f`", $list));
        }
    }
    $out[] = '';

    return count($out) > 3 ? $out : [];
}

/**
 * Tables (with columns) from the up migrations, and the list of migrations.
 *
 * @param string[] $files
 *
 * @return string[]
 */
function context_section_database(string $moduleDir, array $files): array
{
    $migrations = array_values(array_filter($files, static fn (string $f): bool => str_starts_with($f, 'migrations/up/') && str_ends_with($f, '.sql')));
    if ($migrations === []) {
        return [];
    }
    $tables = [];
    foreach ($migrations as $file) {
        $sql = (string) file_get_contents("$moduleDir/$file");
        preg_match_all('/CREATE TABLE(?: IF NOT EXISTS)?\s+`?(?:\{?_DB_PREFIX_\}?|PREFIX_)?([A-Za-z0-9_]+)`?\s*\((.*?)\)\s*ENGINE/is', $sql, $m, PREG_SET_ORDER);
        foreach ($m as $table) {
            preg_match_all('/^\s*`?([a-z0-9_]+)`?\s+(?:INT|TINYINT|SMALLINT|BIGINT|VARCHAR|CHAR|TEXT|LONGTEXT|MEDIUMTEXT|DATETIME|DATE|DECIMAL|FLOAT|DOUBLE|BOOL|BOOLEAN|ENUM|JSON|TIMESTAMP)/im', $table[2], $cols);
            $tables[$table[1]] = $cols[1];
        }
        preg_match_all('/ALTER TABLE\s+`?(?:\{?_DB_PREFIX_\}?|PREFIX_)?([A-Za-z0-9_]+)`?\s+ADD(?: COLUMN)?\s+`?([a-z0-9_]+)`?/i', $sql, $a, PREG_SET_ORDER);
        foreach ($a as $alter) {
            $tables[$alter[1]][] = $alter[2];
        }
    }
    $out = ['### Database', ''];
    foreach ($tables as $table => $columns) {
        $out[] = "- `$table`: " . implode(', ', array_unique($columns));
    }
    $out[] = '- Migrations: ' . implode(', ', array_map(static fn (string $f): string => '`' . basename($f) . '`', $migrations));
    $out[] = '';

    return $out;
}

/**
 * Translation domains with the number of texts, and how complete each language catalogue is.
 *
 * @param string[] $files
 *
 * @return string[]
 */
function context_section_translations(string $repoDir, string $moduleDir, array $files): array
{
    $domains = [];
    foreach ($files as $file) {
        if (preg_match('#^translations/en-US/(.+)\.en-US\.xlf$#', $file, $m)) {
            $domains[$m[1]] = substr_count((string) file_get_contents("$moduleDir/$file"), '<trans-unit');
        }
    }
    $catalogues = [];
    foreach (glob("$repoDir/i18n/*.json") ?: [] as $catalogue) {
        $data = json_decode((string) file_get_contents($catalogue), true);
        $count = 0;
        foreach ((array) ($data['strings'] ?? []) as $texts) {
            $count += count((array) $texts);
        }
        $catalogues[] = basename($catalogue, '.json') . ' ' . $count;
    }
    if ($domains === [] && $catalogues === []) {
        return [];
    }
    $out = ['### Translations', ''];
    $out[] = '- Domains (texts): ' . ($domains === [] ? '—' : implode(', ', array_map(static fn (string $d, int $n): string => "`$d` $n", array_keys($domains), $domains)));
    $out[] = '- Catalogues `i18n/<iso>.json` (entries): ' . ($catalogues === [] ? '—' : implode(', ', $catalogues));
    $out[] = '';

    return $out;
}

/**
