/*
 * Documentation page of one module on the docs site (e.g. https://modules.prestashopheaven.com/<module>/index.php):
 * the manual as PDF in every language. Generated by `ps-module publish site` from this template; the data below is
 * filled in by the build. ?lang=<iso> (or the browser language) puts that language first.
 */

declare(strict_types=1);

/** @var array{module: string, display_name: string, version: string, ps_min: string, ps_tested: string, built: string, languages: array<string, array{native: string, name: string, rtl: bool, display_name: string, description: string, pdf: string, size: int}>} $site */
$site = /* @site */ ['module' => '', 'display_name' => '', 'version' => '', 'ps_min' => '', 'ps_tested' => '', 'built' => '', 'languages' => []];

/**
 * HTML-escapes a text.
 */
function docs_site_e(string $text): string
{
    return htmlspecialchars($text, ENT_QUOTES | ENT_SUBSTITUTE, 'UTF-8');
}

/**
 * The language to show first: ?lang=<iso>, else the first browser language the site has, else English.
 *
 * @param string[] $available
 */
function docs_site_language(array $available): string
{
    $wanted = isset($_GET['lang']) && is_string($_GET['lang']) ? [$_GET['lang']] : [];
    $header = isset($_SERVER['HTTP_ACCEPT_LANGUAGE']) && is_string($_SERVER['HTTP_ACCEPT_LANGUAGE']) ? $_SERVER['HTTP_ACCEPT_LANGUAGE'] : '';
    foreach (explode(',', $header) as $part) {
        $wanted[] = strtolower(substr(trim(explode(';', $part)[0]), 0, 2));
    }
    // Norwegian browsers send nb/nn; the manuals use "no".
    $wanted = array_map(static fn (string $iso): string => in_array($iso, ['nb', 'nn'], true) ? 'no' : $iso, $wanted);
    foreach ($wanted as $iso) {
        if (in_array($iso, $available, true)) {
            return $iso;
        }
    }

    return in_array('en', $available, true) ? 'en' : (string) reset($available);
}

